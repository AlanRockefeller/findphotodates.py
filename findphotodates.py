def compute_samplehash_v1(path, chunk_bytes, num_chunks, algo="blake3"):
    """Compute a fast sample fingerprint from path (size + \0 + chunks).

    For small files (size <= num_chunks * chunk_bytes), hashes the whole file.
    Supports blake3, blake2b(digest_size=16), or sha256.
    Returns hex digest string or None on error.
    """
    try:
        st = os.stat(path)
        size = st.st_size
    except OSError:
        return None

    if algo == "blake3" and _BLAKE3_AVAILABLE:
        h = blake3.blake3()
    elif algo == "sha256":
        h = hashlib.sha256()
    else:
        h = hashlib.blake2b(digest_size=16)

    h.update(str(size).encode("ascii"))
    h.update(b"\0")

    total_sample_bytes = num_chunks * chunk_bytes
    small_file = size <= total_sample_bytes or size == 0

    try:
        with open(path, "rb") as f:
            if small_file:
                # Stream the entire file in chunks to avoid memory blow-up
                for data in iter(lambda: f.read(65536), b""):
                    h.update(data)
            else:
                # Distribute offsets: first 0, last size-chunk_bytes, middle ones spread evenly
                chunks_to_read = []
                end_offset = max(0, size - chunk_bytes)
                for i in range(num_chunks):
                    if i == 0:
                        offset = 0
                    elif i == num_chunks - 1:
                        offset = end_offset
                    else:
                        offset = (
                            (i * end_offset) // (num_chunks - 1)
                            if num_chunks > 1
                            else 0
                        )
                    offset = max(0, min(offset, end_offset))
                    chunks_to_read.append(offset)

                # Deduplicate and sort offsets
                for offset in sorted(set(chunks_to_read)):
                    f.seek(offset)
                    data = f.read(chunk_bytes)
                    if data:
                        h.update(data)
        return h.hexdigest()
    except OSError:
        return None


def compute_fullhash(path, algo="blake3"):
    """Compute full-file hash. algo is 'blake3', 'blake2b', or 'sha256'. Returns hex digest or None."""
    try:
        if algo == "blake3" and _BLAKE3_AVAILABLE:
            h = blake3.blake3()
        elif algo == "blake2b":
            h = hashlib.blake2b()
        elif algo in ("sha256", "blake3"):
            # blake3 requested but not available — fall back to sha256
            h = hashlib.sha256()
        else:
            print(
                f"WARNING: Unknown full-hash algo {algo!r}, falling back to sha256",
                file=sys.stderr,
            )
            h = hashlib.sha256()
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(65536), b""):
                h.update(chunk)
        return h.hexdigest()
    except OSError:
        return None


def open_sqlite_cache(cache_path, debug=False):
    """Create cache dir if needed, open SQLite connection, ensure table exists. Returns connection or None on error."""
    try:
        import sqlite3
    except ImportError:
        if debug:
            print("Debug: sqlite3 module not found.")
        return None
    try:
        Path(cache_path).parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(cache_path, check_same_thread=False)
        conn.execute("PRAGMA journal_mode=WAL;")
        conn.execute("PRAGMA synchronous=NORMAL;")
        conn.execute("""
            CREATE TABLE IF NOT EXISTS hash_cache (
                path TEXT NOT NULL,
                size_bytes INTEGER NOT NULL,
                mtime_ns INTEGER NOT NULL,
                hash_mode TEXT NOT NULL,
                chunk_bytes INTEGER NOT NULL,
                chunks INTEGER NOT NULL,
                algo TEXT NOT NULL,
                digest TEXT NOT NULL,
                PRIMARY KEY (path, size_bytes, mtime_ns, hash_mode, chunk_bytes, chunks, algo)
            )
        """)
        conn.commit()
        return conn
    except Exception as e:
        if debug:
            print(f"Debug: Failed to open hash cache at {cache_path}: {e}")
        return None


def get_cached_hash(
    conn, path, size_bytes, mtime_ns, hash_mode, chunk_bytes, chunks, algo
):
    """Return cached digest string if present, else None."""
    if conn is None:
        return None
    try:
        with _sqlite_lock:
            row = conn.execute(
                """SELECT digest FROM hash_cache
                   WHERE path = ? AND size_bytes = ? AND mtime_ns = ?
                     AND hash_mode = ? AND chunk_bytes = ? AND chunks = ? AND algo = ?""",
                (path, size_bytes, mtime_ns, hash_mode, chunk_bytes, chunks, algo),
            ).fetchone()
        return row[0] if row else None
    except Exception:
        return None


def put_cached_hash(
    conn,
    path,
    size_bytes,
    mtime_ns,
    hash_mode,
    chunk_bytes,
    chunks,
    algo,
    digest,
    pending_counter=None,
):
    """Store digest in cache. If pending_counter is a list [n], batch-commit every HASH_CACHE_BATCH_COMMIT_EVERY."""
    if conn is None:
        return
    try:
        with _sqlite_lock:
            conn.execute(
                """INSERT OR REPLACE INTO hash_cache
                   (path, size_bytes, mtime_ns, hash_mode, chunk_bytes, chunks, algo, digest)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
                (
                    path,
                    size_bytes,
                    mtime_ns,
                    hash_mode,
                    chunk_bytes,
                    chunks,
                    algo,
                    digest,
                ),
            )
            if pending_counter is not None:
                pending_counter[0] += 1
                if pending_counter[0] >= HASH_CACHE_BATCH_COMMIT_EVERY:
                    conn.commit()
                    pending_counter[0] = 0
            else:
                conn.commit()
    except Exception:
        pass


def open_location_cache(cache_path, debug=False):
    """Open SQLite location cache and ensure the expected table exists."""
    try:
        import sqlite3
    except ImportError:
        if debug:
            print("Debug: sqlite3 module not found.")
        return None
    try:
        Path(cache_path).parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(cache_path, check_same_thread=False)
        conn.execute("PRAGMA journal_mode=WAL;")
        conn.execute("PRAGMA synchronous=NORMAL;")
        conn.execute("""
            CREATE TABLE IF NOT EXISTS location_cache (
                lat_rounded REAL NOT NULL,
                lon_rounded REAL NOT NULL,
                precision INTEGER NOT NULL,
                location TEXT NOT NULL,
                fetched_at INTEGER NOT NULL,
                PRIMARY KEY (lat_rounded, lon_rounded, precision)
            )
        """)
        conn.commit()
        return conn
    except Exception as e:
        if debug:
            print(f"Debug: Failed to open location cache at {cache_path}: {e}")
        return None


def get_cached_location(conn, lat_rounded, lon_rounded, precision):
    """Return cached location string if present, else None."""
    if conn is None:
        return None
    try:
        with _sqlite_lock:
            row = conn.execute(
                """SELECT location FROM location_cache
                   WHERE lat_rounded = ? AND lon_rounded = ? AND precision = ?""",
                (lat_rounded, lon_rounded, precision),
            ).fetchone()
        return row[0] if row else None
    except Exception:
        return None


def put_cached_location(
    conn, lat_rounded, lon_rounded, precision, location, pending_counter=None
):
    """Store a resolved location in the SQLite cache."""
    if conn is None or not location or is_coordinate_string(location):
        return
    try:
        with _sqlite_lock:
            conn.execute(
                """INSERT OR REPLACE INTO location_cache
                   (lat_rounded, lon_rounded, precision, location, fetched_at)
                   VALUES (?, ?, ?, ?, ?)""",
                (lat_rounded, lon_rounded, precision, location, int(time.time())),
            )
            if pending_counter is not None:
                pending_counter[0] += 1
                if pending_counter[0] >= LOCATION_CACHE_BATCH_COMMIT_EVERY:
                    conn.commit()
                    pending_counter[0] = 0
            else:
                conn.commit()
    except Exception:
        pass


def get_content_hash(
    key_path,
    size_bytes,
    mtime_ns,
    hash_options,
    hash_conn,
    pending_counter=None,
    os_path=None,
):
    """Return content_hash for a file: from cache or compute. Returns '' if hashing off or restricted by ext.

    key_path is used for cache lookups (normalized for cross-platform reuse).
    os_path is the actual filesystem path for reading (defaults to key_path).
    """
    if hash_options.hash_mode == "off":
        return ""
    ext = (os.path.splitext(key_path)[1] or "").lstrip(".").lower()
    if hash_options.hash_exts is not None and ext not in hash_options.hash_exts:
        return ""
    if os_path is None:
        os_path = key_path
    chunk_bytes = int(hash_options.sample_chunk_mib * 1024 * 1024)
    chunk_bytes = max(1, chunk_bytes)
    if hash_options.hash_mode == "sample":
        cached = get_cached_hash(
            hash_conn,
            key_path,
            size_bytes,
            mtime_ns,
            "sample",
            chunk_bytes,
            hash_options.sample_chunks,
            hash_options.sample_algo,
        )
        if cached is not None:
            return cached
        digest = compute_samplehash_v1(
            os_path,
            chunk_bytes,
            hash_options.sample_chunks,
            algo=hash_options.sample_algo,
        )
        if digest and hash_conn:
            put_cached_hash(
                hash_conn,
                key_path,
                size_bytes,
                mtime_ns,
                "sample",
                chunk_bytes,
                hash_options.sample_chunks,
                hash_options.sample_algo,
                digest,
                pending_counter=pending_counter,
            )
        return digest or ""
    else:
        cached = get_cached_hash(
            hash_conn,
            key_path,
            size_bytes,
            mtime_ns,
            "full",
            0,
            0,
            hash_options.full_algo,
        )
        if cached is not None:
            return cached
        digest = compute_fullhash(os_path, hash_options.full_algo)
        if digest and hash_conn:
            put_cached_hash(
                hash_conn,
                key_path,
                size_bytes,
                mtime_ns,
                "full",
                0,
                0,
                hash_options.full_algo,
                digest,
                pending_counter=pending_counter,
            )
        return digest or ""


def is_supported_file(filename, extensions):
    """Check if a file has a supported extension. If extensions is None, all files match."""
    if extensions is None:
        return True
    return any(filename.lower().endswith(f".{ext}") for ext in extensions)


_IO_ERRNOS = {errno.EIO, errno.ENXIO, errno.ETIMEDOUT, errno.ENODEV}
# Windows: CRC error, not ready, hardware error, I/O device error, device not connected.
_IO_WINERRORS = {21, 23, 483, 1117, 1167}


def _is_io_error(exc):
    """True when an OSError means the drive couldn't read the data (a failing
    or disconnected drive), as opposed to a missing file or a permission problem."""
    return exc.errno in _IO_ERRNOS or getattr(exc, "winerror", None) in _IO_WINERRORS


def _is_windows_reparse_point_dir(entry):
    """Return True if this DirEntry is a Windows directory reparse point
    (junction, directory symlink, or other directory-like reparse target).

    Callers should already have confirmed the entry is a directory
    (entry.is_dir(follow_symlinks=False) == True) before invoking this — we
    only need to decide whether that directory is a reparse point we must
    refuse to recurse into.

    Always False on non-Windows platforms, where st_file_attributes is absent.
    """
    try:
        st = entry.stat(follow_symlinks=False)
    except (PermissionError, OSError):
        return False
    attrs = getattr(st, "st_file_attributes", None)
    if attrs is None:
        return False
    reparse_bit = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)
    return bool(attrs & reparse_bit)


def find_files(directory, extensions, debug=False, errors=None):
    """Recursively find all files with the specified extensions using os.scandir().

    Yields (filepath, is_symlink, size_bytes, mtime_ns) tuples.
    For non-symlink files, size_bytes and mtime_ns come from the DirEntry stat
    cache (no extra syscall on Linux).  For symlinks, they are None so the
    consumer stats the resolved target itself.

    Symlinked directories are NOT recursed into (avoids duplicate traversal and
    infinite loops from symlink cycles).  Symlinked files are still yielded.
    Folders and files that can't be read are skipped; if *errors* is a list,
    (kind, path, is_io_error, message) tuples are appended to it for each one.
    """
    try:
        scan_it = os.scandir(directory)
    except (PermissionError, OSError) as e:
        if errors is not None:
            errors.append(("folder", directory, _is_io_error(e), e.strerror or str(e)))
        return
    with scan_it:
        for entry in scan_it:
            try:
                is_link = entry.is_symlink()
                is_dir_no_follow = entry.is_dir(follow_symlinks=False)
                if is_dir_no_follow:
                    # Alan 5/3/26 - Skip Windows reparse-point *directories*
                    # (NTFS junctions and directory symlinks) to avoid
                    # traversal loops such as
                    # C:\ProgramData\Application Data -> C:\ProgramData.
                    # Only checked for directories so ordinary reparse-point
                    # files (e.g. OneDrive cloud placeholders, file symlinks)
                    # are still indexed normally.
                    if _is_windows_reparse_point_dir(entry):
                        if debug:
                            print(
                                f"Debug: Skipping reparse-point directory: {entry.path}",
                                file=sys.stderr,
                            )
                        continue
                    # Real directory — recurse
                    yield from find_files(entry.path, extensions, debug=debug, errors=errors)
                elif is_link and entry.is_dir(follow_symlinks=True):
                    # Symlinked directory — skip recursion to avoid
                    # duplicate traversal and symlink loops
                    pass
                elif entry.is_file(follow_symlinks=True):
                    if is_supported_file(entry.name, extensions):
                        if is_link:
                            yield entry.path, True, None, None
                        else:
                            st = entry.stat(follow_symlinks=True)
                            yield entry.path, False, st.st_size, st.st_mtime_ns
            except (PermissionError, OSError) as e:
                if errors is not None:
                    errors.append(("file", entry.path, _is_io_error(e), e.strerror or str(e)))
                continue


def _is_read_error_message(message):
    """True for ExifTool errors that mean the file itself couldn't be read
    (as opposed to an unusual or damaged file format)."""
    text = message.lower()
    return any(word in text for word in ("error opening", "error reading", "i/o error",
                                         "input/output", "file not found", "truncated"))


class _ReadThrottle:
    """Limits how many ExifTool workers read the drive at the same time.

    Starts at the worker count; drops to 1 when the drive is struggling so a
    failing disk isn't asked to seek to four damaged places at once.
    """

    def __init__(self, limit):
        self._limit = max(1, limit)
        self._active = 0
        self._cond = threading.Condition()

    @property
    def limit(self):
        return self._limit

    def set_limit(self, limit):
        with self._cond:
            self._limit = max(1, limit)
            self._cond.notify_all()

    def __enter__(self):
        with self._cond:
            while self._active >= self._limit:
                self._cond.wait(0.5)
            self._active += 1
        return self

    def __exit__(self, *exc):
        with self._cond:
            self._active -= 1
            self._cond.notify_all()
        return False


