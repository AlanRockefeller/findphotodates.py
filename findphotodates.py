def run_scan(
    directory,
    output,
    extensions,
    locate=False,
    quiet=False,
    debug=False,
    hash_options=None,
    location_options=None,
    old_format=False,
    perf_stats=None,
    path_style="linux",  # safe internal default; CLI default is "auto" (resolved before calling)
    raw_output=None,  # Alan 5/3/26 - original CLI --output arg, used only for friendly Windows path hints
    workers=4,
    min_image_size=MIN_EXIFTOOL_IMAGE_BYTES,
    retry_blank_exif=False,
    volume_info=None,
):
    """Run a scan on the specified directory.

    If perf_stats is a dict, it will be populated with detailed timing breakdowns.
    volume_info (a DriveInfo) identifies the drive when *directory* is a whole
    drive; it is recorded in the inventory header so the list can be matched
    to its drive later even if the mount point or drive letter changes.
    """
    _t0 = time.time()
    worker_count = _clamp_worker_count(workers)
    min_image_size = _clamp_min_image_size(min_image_size)

    # Resolve "auto" path style once, before any writes.
    if path_style == "auto":
        path_style = resolve_output_path_style("auto", output, directory)

    # Alan 5/3/26 - Validate input + output paths up front. This previously
    # only checked that the input directory existed, and the output path was
    # not validated at all — a bad --output dir would survive a multi-minute
    # scan and then crash at the first checkpoint when tempfile.mkstemp()
    # tried to create the temp file in a non-existent parent directory.
    if not validate_scan_paths(directory, output, raw_output=raw_output):
        return False
    volume_headers = _volume_header_lines(output, directory, volume_info)

    # Alan 9/28/26 - Warn before reading every file on a drive whose last
    # health check found trouble, and go easy on it from the start.
    health_row = _troubling_health_record(directory, volume_info)
    if health_row is not None and not quiet:
        _print_health_warning(health_row)
        if sys.stdin.isatty() and sys.stdout.isatty():
            failing = health_row.get("health") == "FAILING"
            if not _confirm("Scan it anyway?", default=not failing):
                print("Scan cancelled.")
                return False

    if hash_options is None:
        hash_options = parse_hash_args(quiet=quiet)
    if location_options is None:
        location_options = parse_location_args()

    if old_format:
        # Force hashing off for old format
        hash_options.hash_mode = "off"

    hash_conn = (
        open_sqlite_cache(hash_options.hash_cache_path, debug=debug)
        if (hash_options.use_hash_cache and hash_options.hash_mode != "off")
        else None
    )
    hash_cache_pending = [0] if hash_conn else None
    location_conn = (
        open_location_cache(location_options.location_cache_path, debug=debug)
        if (locate and location_options.use_location_cache)
        else None
    )
    location_cache_pending = [0] if location_conn else None

    if not quiet and hash_options.hash_mode != "off":
        msg = f"Hashing enabled ({hash_options.hash_mode})"
        if hash_options.hash_mode == "sample":
            msg += f": {hash_options.sample_chunks}x{hash_options.sample_chunk_mib:g} MiB {hash_options.sample_algo}"
        else:
            msg += f": {hash_options.full_algo}"
        msg += ". First run may be slower; results cached in SQLite."
        print(msg)

    inventory_root = os.path.abspath(directory)
    # Alan 5/3/26 - Existing path check moved into validate_scan_paths() above.

    if not quiet:
        if extensions is None:
            print(f"Indexing all files in '{directory}'...")
        else:
            print(
                f"Searching for files in '{directory}' with extensions: {', '.join(sorted(extensions))}..."
            )

    if not quiet and old_format and output.lower().endswith(".tsv"):
        print(
            "Warning: Using .tsv extension for legacy line-based format. Recommended: .txt"
        )

    # Load existing cache
    _t_cache_start = time.time()
    cache = load_cache(
        output, debug=debug, inventory_root=inventory_root, quiet=quiet
    )
    _t_cache_load = time.time() - _t_cache_start
    if not quiet and cache:
        print(f"Loaded {len(cache)} entries from cache.")

    # Compute the absolute and realpath forms of the output file so we can
    # skip it during discovery (avoids self-indexing when the inventory file
    # lives inside the directory being scanned).
    _output_abs = os.path.abspath(output)
    _output_real = os.path.realpath(output)

    # Redirect warnings to a unique log file per run
    error_log_path = os.path.join(
        tempfile.gettempdir(),
        f"findphotodates.error.{os.getpid()}.{int(time.time())}.log",
    )
    photo_data = []
    file_counts = Counter()
    cached_count = 0
    processed_count = 0
    retry_blank_exif_count = 0
    # Alan 9/28/26 - Track what differs from the previous list for the end-of-scan report.
    had_previous_list = bool(cache)
    new_files = []  # (out_path, size_bytes, mtime_ns) not in the previous list
    # Alan 9/28/26 - Photos that were moved or copied keep their name, size and
    # modification time; reuse their earlier EXIF results instead of re-reading.
    moved_index = None  # (name_lower, size, mtime_ns) -> cached entry, built on first need
    moved_reused_count = 0
    # Alan 9/28/26 - Read problems (e.g. a failing drive). Folder/file errors from
    # the directory walk are collected in discovery.read_errors; these are the rest.
    read_problems = []  # (kind, path, is_io_error, message)
    unreadable_keys = set()  # cache keys of files that couldn't be read
    slow_batches = 0
    struggling = False
    shown_walk_problems = 0  # how many of discovery.read_errors have been printed
    shown_scan_problems = 0  # how many of read_problems have been printed
    MAX_LIVE_READ_PROBLEMS = 20

    def _mark_done(key):
        """The previous list's row for *key* has been replaced by a new one."""
        entry = cache.get(key)
        if entry is not None:
            entry["_seen"] = True

    def _all_read_problems():
        return list(discovery.read_errors) + read_problems

    def _kept_old_rows(final):
        """Rows from the previous list to write back.

        Partial saves (checkpoint, Ctrl-C, disconnect) keep every row the scan
        hasn't reached yet, so stopping never shrinks the list. The final save
        keeps only rows for files in folders, or files, that couldn't be read.
        """
        prefixes = ()
        if final:
            for kind, path, _io, _msg in _all_read_problems():
                key = _normalize_cache_key(os.path.abspath(path))
                if kind == "folder":
                    prefixes += (key.rstrip("/") + "/",)
                else:
                    unreadable_keys.add(key)
            if not prefixes and not unreadable_keys:
                return []
        rows = []
        for key, entry in cache.items():
            if entry.get("_seen"):
                continue
            if final and not (key in unreadable_keys or key.startswith(prefixes)):
                continue
            entry["_kept"] = True
            rows.append(
                (
                    entry.get("filepath") or key,
                    entry.get("date_taken") or "",
                    entry["size_bytes"],
                    entry["mtime_ns"],
                    entry.get("gps_lat") or "",
                    entry.get("gps_lon") or "",
                    entry.get("location") or "",
                    entry.get("content_hash") or "",
                )
            )
        return rows

    def _rows_for_save(final=False):
        return list(photo_data) + _kept_old_rows(final)
    changed_files = []  # out_path whose size or mtime differs from the previous list
    # Detailed timing accumulators
    _t_realpath_total = 0.0
    _t_stat_total = 0.0
    _t_cache_lookup_total = 0.0
    _t_exiftool_total = 0.0
    _t_hashing_total = 0.0
    _t_geolocate_total = 0.0
    _t_checkpoint_total = 0.0
    _t_dispatch_wait = 0.0
    _t_results_wait = 0.0
    _t_worker_total = 0.0
    _worker_details = []

    def cleanup_all():
        if hash_conn is not None:
            try:
                with _sqlite_lock:
                    if hash_cache_pending is not None and hash_cache_pending[0] > 0:
                        hash_conn.commit()
                hash_conn.close()
            except Exception:
                pass
        if location_conn is not None:
            try:
                with _sqlite_lock:
                    if (
                        location_cache_pending is not None
                        and location_cache_pending[0] > 0
                    ):
                        location_conn.commit()
                location_conn.close()
            except Exception:
                pass

    # --- Start background file discovery ---
    file_queue = queue.Queue(maxsize=_DISCOVERY_QUEUE_SIZE)
    discovery = _DiscoveryState()
    producer = threading.Thread(
        target=_discovery_producer,
        args=(file_queue, directory, extensions, discovery, debug),
        daemon=True,
    )
    producer.start()
    _t_discovery_start = time.time()

    interrupted = False

    with (
        _StatusOutputPauseController(enabled=(not quiet and _IS_TTY)) as status_pause,
        open(error_log_path, "w", encoding="utf-8") as error_log,
    ):
        start_time = time.time()
        last_save_time = start_time
        last_progress_time = start_time
        rate_tracker = _RateTracker(window_seconds=30.0)
        discovery_complete = (
            False  # local flag: have we printed the discovery-done message?
        )
        total_files = 0  # set once discovery finishes
        progress_line_len = 0

        work_queue = queue.Queue(maxsize=max(1, worker_count * 4))
        throttle = _ReadThrottle(1 if health_row is not None else worker_count)
        results_queue = queue.Queue()
        stop_event = threading.Event()
        error_log_lock = threading.Lock()
        worker_threads = []
        worker_done_count = 0
        fatal_worker_error = None
        worker_shutdown_timed_out = False
        exiftool_files_queued = 0
        exiftool_metadata_done_count = 0
        exiftool_files_completed = 0

        for worker_id in range(1, worker_count + 1):
            t = threading.Thread(
                target=_exiftool_worker,
                args=(
                    worker_id,
                    work_queue,
                    results_queue,
                    stop_event,
                    locate,
                    hash_options,
                    hash_conn,
                    hash_cache_pending,
                    location_conn,
                    location_cache_pending,
                    error_log,
                    error_log_lock,
                ),
                kwargs={"throttle": throttle},
                daemon=True,
            )
            t.start()
            worker_threads.append(t)

        # Batch buffer for files that need exiftool queries
        # Each entry: (out_path, os_path, key_path, size_bytes, mtime_ns, ext)
        #   out_path  — abspath written to TSV (human-visible)
        #   os_path   — actual filesystem path for exiftool / hashing I/O
        #   key_path  — normalized cache key for TSV cache and hash cache lookups
        exiftool_batch = []

        def _pending_exiftool_files():
            return max(0, exiftool_files_queued - exiftool_metadata_done_count) + len(
                exiftool_batch
            )

        def _pending_final_result_files():
            return max(0, exiftool_metadata_done_count - exiftool_files_completed)

        def _format_exiftool_queue_diag():
            try:
                work_qsize = work_queue.qsize()
            except NotImplementedError:
                work_qsize = "unknown"
            alive = sum(1 for thread in worker_threads if thread.is_alive())
            return (
                f"queued={exiftool_files_queued:,}, "
                f"metadata_done={exiftool_metadata_done_count:,}, "
                f"final_completed={exiftool_files_completed:,}, "
                f"exiftool_pending={_pending_exiftool_files():,}, "
                f"postprocess_pending={_pending_final_result_files():,}, "
                f"work_queue={work_qsize}, alive_workers={alive}"
            )

        def _fit_progress_line(message):
            if not _IS_TTY:
                return message
            width = shutil.get_terminal_size((120, 20)).columns
            if width <= 10 or len(message) < width:
                return message
            return message[: max(1, width - 4)] + "..."

        def _print_progress_line(message):
            nonlocal progress_line_len
            message = _fit_progress_line(message)
            if not _IS_TTY:
                print(message)
                return

            if _ANSI_OK:
                print(f"\r\033[2K{message}", end="\r")
            else:
                padding = " " * max(0, progress_line_len - len(message))
                print(f"\r{message}{padding}", end="\r")
            progress_line_len = len(message)
            sys.stdout.flush()

        def _drain_results():
            nonlocal processed_count, _t_exiftool_total, _t_hashing_total
            nonlocal _t_geolocate_total, _t_results_wait, _t_worker_total
            nonlocal worker_done_count, fatal_worker_error
            nonlocal exiftool_metadata_done_count, exiftool_files_completed
            nonlocal slow_batches
            _trq0 = time.time()
            while True:
                try:
                    packet = results_queue.get_nowait()
                except queue.Empty:
                    break
                if packet.get("type") == "results":
                    rows = packet.get("results", [])
                    input_count = packet.get("input_count", len(rows))
                    if len(rows) != input_count:
                        fatal_worker_error = (
                            "Error: ExifTool worker returned "
                            f"{len(rows):,} row(s) for {input_count:,} queued file(s)."
                        )
                        print(fatal_worker_error, file=sys.stderr)
                        break
                    photo_data.extend(rows)
                    for key in packet.get("keys", ()):
                        _mark_done(key)
                    file_counts.update(packet.get("file_counts", Counter()))
                    processed_count += len(rows)
                    exiftool_files_completed += input_count
                    for path, message in packet.get("read_errors", ()):
                        read_problems.append(("exiftool", path, True, message))
                    if input_count >= 5 and packet.get("t_exiftool", 0.0) / input_count > 10:
                        slow_batches += 1  # >10 s per file: the drive is struggling
                    _t_exiftool_total += packet.get("t_exiftool", 0.0)
                    _t_hashing_total += packet.get("t_hashing", 0.0)
                    _t_geolocate_total += packet.get("t_geolocate", 0.0)
                elif packet.get("type") == "metadata_done":
                    exiftool_metadata_done_count += packet.get("input_count", 0)
                elif packet.get("type") == "worker_done":
                    stats = packet.get("stats", {})
                    _worker_details.append(stats)
                    _t_worker_total += stats.get("wall", 0.0)
                    worker_done_count += 1
                elif packet.get("type") == "fatal_error":
                    if fatal_worker_error is None:
                        fatal_worker_error = packet.get(
                            "message", "Error: ExifTool worker failed."
                        )
                        print(fatal_worker_error, file=sys.stderr)
            _t_results_wait += time.time() - _trq0
            return fatal_worker_error is None

        def _update_progress_and_checkpoint():
            nonlocal last_progress_time, last_save_time, _t_checkpoint_total
            total_seen = cached_count + processed_count
            current_time = time.time()
            rate_tracker.record(current_time, total_seen)

            if not quiet and status_pause.consume_pause_notice():
                _clear_progress_line()
                print("Status output paused for 60 seconds; scan continues.")
            _show_new_read_problems()
            _check_struggling()

            if total_seen > 0 and (current_time - last_save_time) > 900:
                _tc0 = time.time()
                data_snapshot = _rows_for_save()
                _ckpt_ok = _safe_write_inventory(
                    output,
                    data_snapshot,
                    inventory_root,
                    hash_options,
                    old_format,
                    path_style,
                    debug=debug,
                    context="checkpoint",
                    extra_headers=volume_headers,
                )
                _t_checkpoint_total += time.time() - _tc0
                last_save_time = current_time
                if not quiet:
                    _clear_progress_line()
                    if _ckpt_ok:
                        print(f"[Checkpoint: {len(data_snapshot):,} files saved]")
                if not _ckpt_ok:
                    print(
                        "Error: Checkpoint failed; stopping scan so you can "
                        "fix the output path/disk/permissions and rerun."
                    )
                    stop_event.set()
                    return False

            if (
                not quiet
                and not status_pause.is_paused(current_time)
                and (current_time - last_progress_time) >= 2.0
            ):
                elapsed = current_time - start_time
                rate = rate_tracker.rate()
                rate_str = f"{rate:.0f} files/sec" if rate else "..."
                activity = _format_scan_activity(locate, hash_options)
                pending_exiftool = _pending_exiftool_files()
                exiftool_part = (
                    f" — {pending_exiftool:,} in ExifTool queue"
                    if pending_exiftool > 0
                    else ""
                )
                problem_count = len(discovery.read_errors) + len(read_problems)
                if problem_count:
                    exiftool_part += f" — {problem_count:,} unreadable"

                if discovery_complete and total_files > 0:
                    pct = total_seen / total_files * 100
                    eta_str = _format_eta(total_files - total_seen, rate)
                    eta_part = f" — ETA: {eta_str}" if eta_str else ""
                    _print_progress_line(
                        f"{activity}... {total_seen:,} / {total_files:,} ({pct:.1f}%) — "
                        f"{cached_count:,} cached{exiftool_part} — "
                        f"{rate_str}{eta_part} [{_format_duration(elapsed)}]"
                    )
                else:
                    _print_progress_line(
                        f"Discovering and {activity[0].lower() + activity[1:]}... "
                        f"{discovery.discovered:,} found | "
                        f"Processed {total_seen:,} ({cached_count:,} cached) — "
                        f"{rate_str}{exiftool_part} [{_format_duration(elapsed)}]"
                    )
                last_progress_time = current_time
            return True

        def _show_new_read_problems():
            """Print read problems as they happen, up to MAX_LIVE_READ_PROBLEMS."""
            nonlocal shown_walk_problems, shown_scan_problems
            walk_new = discovery.read_errors[shown_walk_problems:]
            scan_new = read_problems[shown_scan_problems:]
            if not walk_new and not scan_new:
                return
            before = shown_walk_problems + shown_scan_problems
            shown_walk_problems += len(walk_new)
            shown_scan_problems += len(scan_new)
            if quiet or before >= MAX_LIVE_READ_PROBLEMS:
                return
            _clear_progress_line()
            for kind, path, _io, message in (walk_new + scan_new)[: MAX_LIVE_READ_PROBLEMS - before]:
                label = {"folder": "Can't open folder", "file": "Can't read"}.get(kind, "Can't read")
                print(f"{label}: {_relative_display(path, inventory_root)} ({message})")
            if shown_walk_problems + shown_scan_problems >= MAX_LIVE_READ_PROBLEMS:
                print(f"(More than {MAX_LIVE_READ_PROBLEMS} read problems; the rest will be "
                      "listed at the end and saved to a file.)")

        def _check_struggling():
            nonlocal struggling
            if struggling:
                return
            io_errors = sum(1 for _k, _p, is_io, _m in _all_read_problems() if is_io)
            if io_errors < 3 and slow_batches < 2:
                return
            struggling = True
            throttle.set_limit(1)
            if not quiet:
                _clear_progress_line()
                what = (f"{io_errors:,} read errors so far" if io_errors >= 3
                        else "reading has become extremely slow")
                print(_wrap(
                    f"Warning: this drive is having trouble reading files ({what}). It may be "
                    "failing. The scan will now read one file at a time to go easier on it. "
                    "If this drive holds the only copy of anything, press Ctrl-C to stop "
                    "(progress is saved) and copy your files off it first. A health check "
                    "(h in the menu, or --health) shows the drive's condition.", indent=""))

        def _maybe_print_discovery_complete():
            nonlocal discovery_complete, total_files
            if not discovery_complete and discovery.done.is_set():
                discovery_complete = True
                total_files = discovery.total
                if not quiet:
                    _clear_progress_line()
                    print(f"Discovery complete: {total_files:,} files found.")

        def _record_blank_exif_batch(batch):
            nonlocal processed_count, _t_hashing_total
            blank_results = {item[1]: (None, None, None) for item in batch}
            rows, counts, stats = _build_exiftool_rows(
                batch,
                blank_results,
                locate,
                location_conn,
                location_cache_pending,
                hash_options,
                hash_conn,
                hash_cache_pending,
            )
            photo_data.extend(rows)
            for item in batch:
                _mark_done(item[2])
            file_counts.update(counts)
            processed_count += len(rows)
            _t_hashing_total += stats["t_hashing"]

        def _index_as_non_media(out_path, fs_path, key_path, size_bytes, mtime_ns, ext):
            nonlocal processed_count, _t_hashing_total
            _th0 = time.time()
            content_hash = get_content_hash(
                key_path,
                size_bytes,
                mtime_ns,
                hash_options,
                hash_conn,
                hash_cache_pending,
                os_path=fs_path,
            )
            _t_hashing_total += time.time() - _th0
            photo_data.append(
                (
                    out_path,
                    "",
                    size_bytes,
                    mtime_ns,
                    "",
                    "",
                    "",
                    content_hash,
                )
            )
            _mark_done(key_path)
            processed_count += 1
            file_counts[ext] += 1

        def _enqueue_exiftool_batch():
            nonlocal exiftool_files_queued
            if not exiftool_batch:
                return True
            batch = list(exiftool_batch)
            exiftool_batch.clear()
            while True:
                try:
                    work_queue.put(batch, timeout=0.5)
                    exiftool_files_queued += len(batch)
                    return True
                except queue.Full:
                    if not _drain_results():
                        return False
                    _maybe_print_discovery_complete()
                    if not _update_progress_and_checkpoint():
                        return False
                    if not any(t.is_alive() for t in worker_threads):
                        _log_worker_error(
                            error_log,
                            error_log_lock,
                            f"Warning: all ExifTool workers stopped; recording {len(batch)} file(s) with blank EXIF.",
                        )
                        _record_blank_exif_batch(batch)
                        return True

        def _stop_workers(interrupt=False):
            nonlocal worker_shutdown_timed_out
            if interrupt:
                stop_event.set()
                for _ in worker_threads:
                    try:
                        work_queue.put_nowait(None)
                    except queue.Full:
                        pass
            else:
                for _ in worker_threads:
                    work_queue.put(None)
            timeout_seconds = 5 if interrupt else WORKER_SHUTDOWN_TIMEOUT_SECONDS
            deadline = time.time() + timeout_seconds
            while any(t.is_alive() for t in worker_threads):
                for t in worker_threads:
                    remaining = max(0.0, deadline - time.time())
                    if remaining <= 0:
                        alive = sum(1 for thread in worker_threads if thread.is_alive())
                        if alive:
                            worker_shutdown_timed_out = True
                            print(
                                f"Warning: {alive} ExifTool worker(s) did not exit within {timeout_seconds} seconds; abandoning; failing scan. "
                                f"ExifTool state: {_format_exiftool_queue_diag()}",
                                file=sys.stderr,
                            )
                        return False
                    t.join(timeout=min(0.2, remaining))
                _drain_results()
                if not interrupt:
                    _update_progress_and_checkpoint()
            _drain_results()
            return True

        def _wait_for_exiftool_drain():
            # Alan 5/8/26 - Drain queued metadata batches before normal shutdown;
            # the shutdown timeout is only for worker exit, not backlog processing.
            last_metadata_done = exiftool_metadata_done_count
            last_progress_time_for_diag = time.time()
            last_diag_time = last_progress_time_for_diag
            while exiftool_metadata_done_count < exiftool_files_queued:
                if not _drain_results():
                    return False
                _maybe_print_discovery_complete()
                if not _update_progress_and_checkpoint():
                    return False

                pending = exiftool_files_queued - exiftool_metadata_done_count
                if pending <= 0:
                    break

                if not any(t.is_alive() for t in worker_threads):
                    print(
                        "Error: ExifTool workers exited before all queued metadata work completed. "
                        f"ExifTool state: {_format_exiftool_queue_diag()}",
                        file=sys.stderr,
                    )
                    return False

                now = time.time()
                if exiftool_metadata_done_count != last_metadata_done:
                    last_metadata_done = exiftool_metadata_done_count
                    last_progress_time_for_diag = now
                elif now - last_progress_time_for_diag >= 300 and now - last_diag_time >= 300:
                    print(
                        "Warning: still waiting for ExifTool metadata work to drain. "
                        f"ExifTool state: {_format_exiftool_queue_diag()}",
                        file=sys.stderr,
                    )
                    last_diag_time = now
                if (
                    now - last_progress_time_for_diag
                    >= EXIFTOOL_DRAIN_NO_PROGRESS_TIMEOUT_SECONDS
                ):
                    print(
                        "Error: ExifTool metadata work made no progress before the drain timeout. "
                        f"ExifTool state: {_format_exiftool_queue_diag()}",
                        file=sys.stderr,
                    )
                    return False
                time.sleep(0.2)

            return _drain_results()

        try:
            while True:
                if not _drain_results():
                    _stop_workers(interrupt=True)
                    cleanup_all()
                    return False
                _maybe_print_discovery_complete()
                if not _update_progress_and_checkpoint():
                    _stop_workers(interrupt=True)
                    cleanup_all()
                    return False

                try:
                    _td0 = time.time()
                    item = file_queue.get(timeout=0.5)
                    _t_dispatch_wait += time.time() - _td0
                except queue.Empty:
                    _t_dispatch_wait += time.time() - _td0
                    if discovery.done.is_set() and file_queue.empty():
                        if discovery.error is not None:
                            print(f"\nError during file discovery: {discovery.error}")
                            raise discovery.error from None
                        break
                    continue

                if item is None:
                    if discovery.error is not None:
                        if not quiet:
                            print(f"\nError during file discovery: {discovery.error}")
                        raise discovery.error
                    break

                file, is_symlink, prod_size, prod_mtime = item
                basename = os.path.basename(file)
                ext = os.path.splitext(basename)[1].lstrip(".").lower()

                try:
                    out_path = os.path.abspath(file)
                    # Skip the inventory file itself to avoid self-indexing
                    if out_path == _output_abs or out_path == _output_real:
                        continue
                    # key_path is always derived from out_path (what's stored in
                    # the TSV) so that cache lookups match what load_cache keys on.
                    key_path = _normalize_cache_key(out_path)
                    if is_symlink:
                        # Symlink: resolve target for I/O (stat, exiftool, hashing)
                        _tr0 = time.time()
                        fs_path = os.path.realpath(out_path)
                        _t_realpath_total += time.time() - _tr0
                        # Skip if symlink target is the inventory file
                        if fs_path == _output_real:
                            continue
                        _ts0 = time.time()
                        stat_info = os.stat(fs_path)
                        size_bytes = stat_info.st_size
                        mtime_ns = stat_info.st_mtime_ns
                        _t_stat_total += time.time() - _ts0
                    else:
                        # Non-symlink: reuse producer-side metadata (no stat syscall)
                        fs_path = out_path
                        size_bytes = prod_size
                        mtime_ns = prod_mtime

                    # Check TSV cache
                    _tcl0 = time.time()
                    cached_entry = cache.get(key_path)
                    _t_cache_lookup_total += time.time() - _tcl0

                    cache_valid = (
                        cached_entry
                        and cached_entry["size_bytes"] == size_bytes
                        and cached_entry["mtime_ns"] == mtime_ns
                    )
                    if cached_entry is None:
                        if had_previous_list:
                            new_files.append((out_path, size_bytes, mtime_ns))
                    elif not cache_valid:
                        changed_files.append(out_path)
                    retry_cached_blank_exif = False
                    if cache_valid:
                        # Alan 5/8/26 - Retry blank EXIF cache rows so interrupted TSV inventories can be repaired.
                        retry_cached_blank_exif = _should_retry_blank_exif(
                            key_path, cached_entry, retry_blank_exif
                        )
                        if retry_cached_blank_exif:
                            retry_blank_exif_count += 1
                            if debug:
                                print(
                                    f"Debug: Retrying blank EXIF cache row: {out_path}"
                                )

                    source_entry = (
                        cached_entry if cache_valid and not retry_cached_blank_exif else None
                    )
                    reused_moved = False
                    if (
                        cached_entry is None
                        and had_previous_list
                        and size_bytes
                        and ext in EXIFTOOL_EXTENSIONS
                    ):
                        if moved_index is None:
                            moved_index = _build_moved_index(cache)
                        moved_entry = moved_index.get(
                            (key_path.rsplit("/", 1)[-1].lower(), size_bytes, mtime_ns)
                        )
                        if moved_entry is not None and not (
                            retry_blank_exif and not moved_entry.get("date_taken")
                        ):
                            source_entry = moved_entry
                            reused_moved = True

                    if source_entry is not None:
                        date_taken = source_entry["date_taken"]
                        gps_lat = source_entry.get("gps_lat")
                        gps_lon = source_entry.get("gps_lon")
                        location = source_entry.get("location")

                        if locate and gps_lat and gps_lon:
                            if not location or is_coordinate_string(location):
                                _tg0 = time.time()
                                location = geolocate(
                                    gps_lat,
                                    gps_lon,
                                    location_conn=location_conn,
                                    pending_counter=location_cache_pending,
                                )
                                _t_geolocate_total += time.time() - _tg0
                                source_entry["location"] = location

                        _th0 = time.time()
                        content_hash = get_content_hash(
                            key_path,
                            size_bytes,
                            mtime_ns,
                            hash_options,
                            hash_conn,
                            hash_cache_pending,
                            os_path=fs_path,
                        )
                        _t_hashing_total += time.time() - _th0
                        photo_data.append(
                            (
                                out_path,
                                date_taken or "",
                                size_bytes,
                                mtime_ns,
                                gps_lat or "",
                                gps_lon or "",
                                location or "",
                                content_hash,
                            )
                        )
                        cached_count += 1
                        _mark_done(key_path)
                        if reused_moved:
                            moved_reused_count += 1
                        # fall through to progress/checkpoint below

                    else:
                        # Not cached, stale, or forced retry — check if exiftool-eligible
                        if ext in EXIFTOOL_EXTENSIONS:
                            # Tiny images (icons, thumbnails) almost never have EXIF.
                            # RAW/video/other EXIFTOOL_EXTENSIONS are not filtered.
                            skip_for_size = (
                                not retry_cached_blank_exif
                                and min_image_size > 0
                                and ext in SIZE_FILTERED_IMAGE_EXTENSIONS
                                and size_bytes < min_image_size
                            )
                            if skip_for_size:
                                _index_as_non_media(
                                    out_path,
                                    fs_path,
                                    key_path,
                                    size_bytes,
                                    mtime_ns,
                                    ext,
                                )
                            else:
                                exiftool_batch.append(
                                    (
                                        out_path,
                                        fs_path,
                                        key_path,
                                        size_bytes,
                                        mtime_ns,
                                        ext,
                                    )
                                )
                                if len(exiftool_batch) >= EXIFTOOL_BATCH_SIZE:
                                    if not _enqueue_exiftool_batch():
                                        _stop_workers(interrupt=True)
                                        cleanup_all()
                                        return False
                        else:
                            # Non-media file: index with filesystem metadata only
                            _index_as_non_media(
                                out_path,
                                fs_path,
                                key_path,
                                size_bytes,
                                mtime_ns,
                                ext,
                            )
                    if source_entry is not None:
                        file_counts[ext] += 1

                except OSError as e:
                    error_log.write(f"Warning: Could not access '{file}': {str(e)}\n")
                    read_problems.append(("file", file, _is_io_error(e), e.strerror or str(e)))
                    # Alan 9/28/26 - One unreadable file on a failing drive is not a
                    # disconnect; stop only if the drive itself is gone.
                    if _root_gone(inventory_root) and any(
                        err in str(e).lower()
                        for err in [
                            "no such file",
                            "input/output error",
                            "stale file handle",
                        ]
                    ):
                        _stop_workers(interrupt=True)
                        _drain_results()
                        if _check_drive_disconnect(
                            e,
                            output,
                            _rows_for_save(),
                            inventory_root,
                            hash_options,
                            old_format,
                            cleanup_all,
                            path_style=path_style,
                            extra_headers=volume_headers,
                        ):
                            return False
                    continue

            if not _enqueue_exiftool_batch():
                _stop_workers(interrupt=True)
                cleanup_all()
                return False
            if not _wait_for_exiftool_drain():
                _stop_workers(interrupt=True)
                _drain_results()
                cleanup_all()
                return False
            workers_finished = _stop_workers(interrupt=False)
            if fatal_worker_error is not None:
                _stop_workers(interrupt=True)
                _drain_results()
                cleanup_all()
                return False
            if not workers_finished:
                _stop_workers(interrupt=True)
                _drain_results()
                cleanup_all()
                return False
            done_deadline = time.time() + 10
            while worker_done_count < worker_count:
                if not _drain_results():
                    _stop_workers(interrupt=True)
                    cleanup_all()
                    return False
                if worker_done_count >= worker_count:
                    break
                if time.time() >= done_deadline:
                    missing = worker_count - worker_done_count
                    print(
                        f"Warning: missing {missing} ExifTool worker completion packet(s); failing scan.",
                        file=sys.stderr,
                    )
                    _stop_workers(interrupt=True)
                    _drain_results()
                    cleanup_all()
                    return False
                time.sleep(0.05)

        except Exception:
            _stop_workers(interrupt=True)
            _drain_results()
            raise
        except KeyboardInterrupt:
            interrupted = True
            status_pause.stop()
            _clear_progress_line()
            print(
                f"\nInterrupted by Ctrl-C after collecting {len(photo_data):,} file rows."
            )
            print("Stopping workers and saving a resumable partial inventory...")
            try:
                _stop_workers(interrupt=True)
            except KeyboardInterrupt:
                print(
                    "Second Ctrl-C received while stopping workers; skipping worker wait."
                )
            try:
                _drain_results()
            except KeyboardInterrupt:
                print(
                    "Second Ctrl-C received while collecting final worker results."
                )
            # Alan 5/3/26 - _safe_write_inventory already prints a friendly
            # error block on predictable failures; only show a generic
            # warning for unexpected exceptions.
            saved_progress = False
            try:
                saved_rows = _rows_for_save()
                if _safe_write_inventory(
                    output,
                    saved_rows,
                    inventory_root,
                    hash_options,
                    old_format,
                    path_style,
                    debug=debug,
                    context="interrupted save",
                    extra_headers=volume_headers,
                ):
                    saved_progress = True
                    print(f"Saved {len(saved_rows):,} rows to '{output}' "
                          f"({len(photo_data):,} from this scan, the rest from the previous list).")
            except KeyboardInterrupt:
                print(
                    "Second Ctrl-C received while saving; the partial inventory may not have been written."
                )
            except Exception as save_err:
                print(f"WARNING: Could not save progress: {save_err}")
            try:
                _show_new_read_problems()
                problems = _all_read_problems()
                if problems:
                    report_read_problems(problems, output, None, quiet=quiet)
            except KeyboardInterrupt:
                pass
            if saved_progress:
                print("\nTo resume, run the same command again.")
                print(
                    "Existing rows in the TSV will be used as cache, so the scan picks up from saved progress."
                )
            else:
                print("\nNo resumable progress file was saved for this interrupt.")

    # Wait for producer thread to finish (should already be done)
    try:
        producer.join(timeout=0.2 if interrupted else 5)
    except KeyboardInterrupt:
        interrupted = True

    if interrupted:
        try:
            cleanup_all()
        except KeyboardInterrupt:
            pass
        return False
    if worker_shutdown_timed_out:
        cleanup_all()
        return False

    total_seen = cached_count + processed_count
    if total_seen == 0:
        if not quiet:
            print("No files found.")
        cleanup_all()
        return True

    if not quiet:
        elapsed = time.time() - start_time
        # Clear \r progress line, then print clean completion summary
        _clear_progress_line()
        print(
            f"Processing complete: {total_seen:,} files in {_format_duration(elapsed)}."
        )

    _tw0 = time.time()
    # Alan 5/3/26 - Wrap final write in _safe_write_inventory so the user
    # gets a friendly error (not a Python traceback) if the output dir
    # disappeared, filled up, or revoked write access during the scan.
    final_rows = _rows_for_save(final=True)
    _final_ok = _safe_write_inventory(
        output,
        final_rows,
        inventory_root,
        hash_options,
        old_format,
        path_style,
        debug=debug,
        context="final write",
        extra_headers=volume_headers,
    )
    _t_write = time.time() - _tw0

    if not _final_ok:
        cleanup_all()
        return False

    if not quiet:
        print(f"Dates written to '{output}' ({len(final_rows):,} files listed).")
        if cached_count > 0:
            print(
                f"  ({cached_count:,} from cache, {processed_count:,} newly processed)"
            )
        if moved_reused_count:
            print(
                f"  {moved_reused_count:,} moved or copied photos/videos reused their "
                "earlier dates without being read again"
            )
        if retry_blank_exif:
            print(f"Blank EXIF rows retried: {retry_blank_exif_count:,}")

    summarize_results(photo_data, file_counts, quiet, debug)
    if not quiet:
        if had_previous_list:
            removed = [
                (key, entry["size_bytes"], entry["mtime_ns"])
                for key, entry in cache.items()
                if not entry.get("_seen") and not entry.get("_kept")
            ]
            print_change_report(
                inventory_root, new_files, changed_files, removed, extensions is not None
            )
        else:
            print("\nThis is a new file list, so there is no earlier scan to compare with.")
    problems = _all_read_problems()
    if problems:
        report_read_problems(problems, output, len(final_rows) - len(photo_data), quiet=quiet)
    cleanup_all()

    if perf_stats is not None:
        _t_total = time.time() - _t0
        # Discovery wall time = producer thread lifetime
        _t_discovery_wall = (
            discovery.done_time - _t_discovery_start if discovery.done_time else 0.0
        )
        perf_stats["wall_total"] = _t_total
        perf_stats["t_cache_load"] = _t_cache_load
        perf_stats["t_discovery_wall"] = _t_discovery_wall
        perf_stats["t_discovery_walk"] = discovery.t_walk
        perf_stats["t_discovery_queue_wait"] = discovery.t_queue_wait
        perf_stats["t_realpath"] = _t_realpath_total
        perf_stats["t_stat"] = _t_stat_total
        perf_stats["t_cache_lookup"] = _t_cache_lookup_total
        perf_stats["t_exiftool"] = _t_exiftool_total
        perf_stats["t_hashing"] = _t_hashing_total
        perf_stats["t_geolocate"] = _t_geolocate_total
        perf_stats["t_checkpoints"] = _t_checkpoint_total
        perf_stats["t_dispatch_wait"] = _t_dispatch_wait
        perf_stats["t_results_wait"] = _t_results_wait
        perf_stats["t_worker_total"] = _t_worker_total
        perf_stats["worker_details"] = sorted(
            _worker_details, key=lambda item: item.get("worker_id", 0)
        )
        perf_stats["worker_count"] = worker_count
        perf_stats["t_write"] = _t_write
        perf_stats["files_total"] = total_seen
        perf_stats["files_cached"] = cached_count
        perf_stats["files_moved_reused"] = moved_reused_count
        perf_stats["files_processed"] = processed_count
        perf_stats["retry_blank_exif_count"] = retry_blank_exif_count

    return True


def _print_perf_summary(label, stats):
    """Print a performance timing breakdown for a single scan."""
    wall = stats.get("wall_total", 0)
    if wall <= 0:
        return
    worker_count = stats.get("worker_count", 1)
    print(f"\n--- Timing breakdown (overlapping; not additive): {label} ---")
    items = [
        ("Inventory cache load", stats.get("t_cache_load", 0), True),
        ("Discovery (wall)", stats.get("t_discovery_wall", 0), True),
        ("  scandir walk", stats.get("t_discovery_walk", 0), True),
        ("  queue put-wait", stats.get("t_discovery_queue_wait", 0), True),
        ("realpath() calls", stats.get("t_realpath", 0), True),
        ("stat() calls", stats.get("t_stat", 0), True),
        ("TSV cache lookups", stats.get("t_cache_lookup", 0), True),
        ("Dispatch wait", stats.get("t_dispatch_wait", 0), True),
        ("Results drain", stats.get("t_results_wait", 0), True),
        (f"ExifTool ({worker_count}w sum)", stats.get("t_exiftool", 0), False),
        (
            f"Content hashing ({worker_count}w sum)",
            stats.get("t_hashing", 0),
            False,
        ),
        (f"Geolocation ({worker_count}w sum)", stats.get("t_geolocate", 0), False),
        ("Checkpoints", stats.get("t_checkpoints", 0), True),
        ("Final write", stats.get("t_write", 0), True),
    ]
    for name, secs, show_pct in items:
        if show_pct:
            pct = secs / wall * 100 if wall else 0
            print(f"  {name:<26s} {secs:7.2f}s  ({pct:5.1f}% of wall)")
        else:
            print(f"  {name:<26s} {secs:7.2f}s  (sum across workers)")
    print(f"  {'Wall total':<26s} {wall:7.2f}s")
    worker_details = stats.get("worker_details") or []
    worker_active_total = sum(item.get("t_active", 0) for item in worker_details)
    if worker_active_total:
        print(
            f"  {'Worker active total':<26s} {worker_active_total:7.2f}s  (parallel; sum exceeds wall by design)"
        )
    if worker_details:
        print("  Per-worker:")
        for item in worker_details:
            print(
                "    "
                f"#{item.get('worker_id', 0):<2d} "
                f"wall={item.get('wall', 0):.2f}s "
                f"active={item.get('t_active', 0):.2f}s "
                f"exif={item.get('t_exiftool', 0):.2f}s "
                f"hash={item.get('t_hashing', 0):.2f}s "
                f"geo={item.get('t_geolocate', 0):.2f}s "
                f"push={item.get('t_queue_push', 0):.2f}s "
                f"files={item.get('files', 0):,} "
                f"errors={item.get('errors', 0)}"
            )
    total = stats.get("files_total", 0)
    cached = stats.get("files_cached", 0)
    processed = stats.get("files_processed", 0)
    print(f"  Files: {total:,} total ({cached:,} cached, {processed:,} processed)")
    retried = stats.get("retry_blank_exif_count", 0)
    if retried:
        print(f"  Blank EXIF rows retried: {retried:,}")


def add_hashes_to_inventory(
    tsv_path,
    hash_options,
    quiet=False,
    debug=False,
    path_style="linux",  # safe internal default; CLI default is "auto" (resolved before calling)
):
    """Fill in missing content hashes for an existing inventory TSV.

    Reads the TSV, computes hashes for rows with blank content_hash
    (where the file still exists and matches size/mtime), writes back.
    Uses the SQLite hash cache to avoid recomputing known hashes.
    """
    if not os.path.exists(tsv_path):
        print(f"Error: Inventory file '{tsv_path}' not found.")
        return False

    if hash_options.hash_mode == "off":
        print(
            "Error: --add-hashes requires hashing to be enabled. Use --hash sample or --hash full."
        )
        return False

    # Read existing TSV data
    # We use load_cache-style parsing but need the full rows including content_hash
    rows = []  # list of dicts with all TSV columns
    comment_lines = []  # preserve header comments
    header_line = None

    try:
        with open(tsv_path, "r", encoding="utf-8", newline="") as f:
            for line in f:
                line = line.rstrip("\n\r")
                if not line:
                    continue
                if line.startswith("#"):
                    comment_lines.append(line)
                    continue
                if header_line is None:
                    header_line = line
                    # Validate that this looks like the expected TSV header
                    header_fields = header_line.split("\t")
                    if header_fields[0] != "filepath":
                        print(
                            f"Error: Expected TSV header starting with 'filepath', got: {header_fields[0]!r}"
                        )
                        print(
                            f"  File '{tsv_path}' does not appear to be a valid findphotodates inventory."
                        )
                        return False
                    continue
                # Data row — use csv.reader to handle quoted fields containing
                # tabs (the writer uses csv.writer with QUOTE_MINIMAL).
                # Pad with empty strings if row has fewer fields than
                # TSV_COLUMNS (e.g. older inventories without content_hash).
                parts = next(csv.reader([line], delimiter="\t"))
                if len(parts) > len(TSV_COLUMNS):
                    if not quiet:
                        print(
                            f"WARNING: Row has {len(parts)} fields, expected {len(TSV_COLUMNS)}; "
                            f"extra fields will be dropped: {parts[0]!r}"
                        )
                row = dict(
                    zip(
                        TSV_COLUMNS,
                        parts + [""] * (len(TSV_COLUMNS) - len(parts)),
                        strict=False,
                    )
                )
                rows.append(row)
    except (IOError, UnicodeDecodeError) as e:
        print(f"Error reading '{tsv_path}': {e}")
        return False

    if not rows:
        if not quiet:
            print(f"No data rows found in '{tsv_path}'.")
        return True

    # Count how many need hashes
    need_hash = [r for r in rows if not r.get("content_hash", "").strip()]
    if not need_hash:
        if not quiet:
            print(f"All {len(rows)} rows already have content hashes.")
        return True

    if not quiet:
        print(
            f"Loaded {len(rows)} rows from '{tsv_path}'. {len(need_hash)} missing hashes."
        )
        msg = f"Hashing mode: {hash_options.hash_mode}"
        if hash_options.hash_mode == "sample":
            msg += f" ({hash_options.sample_chunks}x{hash_options.sample_chunk_mib:g} MiB {hash_options.sample_algo})"
        print(msg)

    # Open hash cache
    hash_conn = (
        open_sqlite_cache(hash_options.hash_cache_path, debug=debug)
        if (hash_options.use_hash_cache and hash_options.hash_mode != "off")
        else None
    )
    hash_cache_pending = [0] if hash_conn else None

    filled = 0
    skipped = 0
    errors = 0
    interrupted = False
    start_time = time.time()
    last_progress_time = start_time

    try:
        with _StatusOutputPauseController(
            enabled=(not quiet and _IS_TTY)
        ) as status_pause:
            for row in rows:
                if row.get("content_hash", "").strip():
                    continue  # already has hash

                filepath = row.get("filepath", "")
                if not filepath:
                    continue

                try:
                    # key_path from stored filepath (matches load_cache keying)
                    key_path = _normalize_cache_key(filepath)
                    # Resolve cross-platform display paths back to a local path
                    # before following symlinks for stat/hash I/O.
                    real_path = os.path.realpath(_resolve_local_inventory_path(filepath))
                    stat_info = os.stat(real_path)
                    size_bytes = stat_info.st_size
                    mtime_ns = stat_info.st_mtime_ns

                    # Verify file hasn't changed since indexing
                    row_size = int(row.get("size_bytes", 0))
                    row_mtime = int(row.get("mtime_ns", 0))
                    if row_size != size_bytes or row_mtime != mtime_ns:
                        if debug:
                            print(f"  Skipping (changed): {filepath}")
                        skipped += 1
                        continue

                    content_hash = get_content_hash(
                        key_path,
                        size_bytes,
                        mtime_ns,
                        hash_options,
                        hash_conn,
                        hash_cache_pending,
                        os_path=real_path,
                    )
                    if content_hash:
                        row["content_hash"] = content_hash
                        filled += 1
                    else:
                        errors += 1

                except OSError:
                    skipped += 1
                    continue

                # Progress every 2 seconds
                if not quiet:
                    current_time = time.time()
                    if status_pause.consume_pause_notice():
                        _clear_progress_line()
                        print("Status output paused for 60 seconds; hashing continues.")
                    if (
                        not status_pause.is_paused(current_time)
                        and current_time - last_progress_time >= 2.0
                    ):
                        elapsed = current_time - start_time
                        print(
                            f"  Hashed {filled:,} / {len(need_hash):,} — {skipped} skipped, {errors} errors [{_format_duration(elapsed)}]",
                            end="\r" if _IS_TTY else "\n",
                        )
                        last_progress_time = current_time

    except KeyboardInterrupt:
        interrupted = True
        print(f"\n\nInterrupted! {filled:,} hashes computed so far.")
        if filled > 0:
            print("Saving partial progress...")
        else:
            print("No hashes were added. File unchanged.")

    # Commit any pending hash cache writes
    if hash_conn:
        try:
            if hash_cache_pending and hash_cache_pending[0] > 0:
                hash_conn.commit()
            hash_conn.close()
        except Exception:
            pass

    if not interrupted and not quiet:
        elapsed = time.time() - start_time
        print(
            f"\n  Done: {filled:,} hashes added, {skipped} skipped, {errors} errors [{_format_duration(elapsed)}]"
        )

    if filled == 0:
        if not interrupted and not quiet:
            print("No hashes were added. File unchanged.")
        return not interrupted

    # Reconstruct the hash_options comment lines to reflect current settings
    # Update or add hash_mode/content_hash_format headers
    new_comments = []
    has_hash_mode = False
    has_hash_format = False
    for line in comment_lines:
        if line.startswith("# inventory_root="):
            root = line.split("=", 1)[1]
            new_comments.append(
                f"# inventory_root={format_path_style(root, path_style)}"
            )
        elif line.startswith("# hash_mode="):
            new_comments.append(f"# hash_mode={hash_options.hash_mode}")
            has_hash_mode = True
        elif line.startswith("# content_hash_format="):
            if hash_options.hash_mode == "sample":
                new_comments.append("# content_hash_format=samplehash_v1")
            elif hash_options.hash_mode == "full":
                new_comments.append("# content_hash_format=fullhash_v1")
            has_hash_format = True
        elif line.startswith("# samplehash_v1 ") and hash_options.hash_mode == "sample":
            new_comments.append(
                f"# samplehash_v1 algo={hash_options.sample_algo} chunks={hash_options.sample_chunks} chunk_mib={hash_options.sample_chunk_mib:g}"
            )
        elif line.startswith("# fullhash ") and hash_options.hash_mode == "full":
            new_comments.append(f"# fullhash algo={hash_options.full_algo}")
        else:
            new_comments.append(line)

    # Add headers if they didn't exist
    insert_pos = len(new_comments)
    for i, line in enumerate(new_comments):
        if line == TSV_HEADER:
            insert_pos = i
            break
    if not has_hash_mode:
        new_comments.insert(insert_pos, f"# hash_mode={hash_options.hash_mode}")
        insert_pos += 1
    if not has_hash_format:
        if hash_options.hash_mode == "sample":
            new_comments.insert(insert_pos, "# content_hash_format=samplehash_v1")
            insert_pos += 1
            new_comments.insert(
                insert_pos,
                f"# samplehash_v1 algo={hash_options.sample_algo} chunks={hash_options.sample_chunks} chunk_mib={hash_options.sample_chunk_mib:g}",
            )
        elif hash_options.hash_mode == "full":
            new_comments.insert(insert_pos, "# content_hash_format=fullhash_v1")
            insert_pos += 1
            new_comments.insert(insert_pos, f"# fullhash algo={hash_options.full_algo}")

    # Write back atomically
    output_dir = os.path.dirname(os.path.abspath(tsv_path))
    fd, temp_file = tempfile.mkstemp(
        dir=output_dir, suffix=".tsv", prefix=".findphotodates_"
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as f:
            for line in new_comments:
                f.write(line + "\n")
            writer = csv.writer(f, delimiter="\t", quoting=csv.QUOTE_MINIMAL)
            writer.writerow(TSV_COLUMNS)
            sorted_rows = sorted(rows, key=lambda r: r.get("filepath", ""))
            for row in sorted_rows:
                writer.writerow(
                    [
                        format_path_style(row.get("filepath", ""), path_style),
                        row.get("date_taken", ""),
                        row.get("size_bytes", ""),
                        row.get("mtime_ns", ""),
                        row.get("gps_lat", ""),
                        row.get("gps_lon", ""),
                        row.get("location", ""),
                        row.get("content_hash", ""),
                    ]
                )
        os.replace(temp_file, tsv_path)
    except Exception:
        try:
            os.unlink(temp_file)
        except Exception:
            pass
        raise

    if interrupted:
        remaining = len(need_hash) - filled - skipped - errors
        print(
            f"Saved {filled:,} hashes to '{tsv_path}'. {remaining:,} rows still need hashes."
        )
        print("\nTo resume, run the same command again:")
        print(f'  findphotodates.py -o "{tsv_path}" --add-hashes')
        print("Already-hashed rows will be skipped automatically.")
        return False

    if not quiet:
        print(f"Updated '{tsv_path}' with {filled:,} new hashes.")
    return True


