def _wrap(text, indent="     "):
    import textwrap

    width = max(40, min(shutil.get_terminal_size((88, 20)).columns, 100) - 2)
    return "\n".join(
        textwrap.fill(p, width=width, initial_indent=indent, subsequent_indent=indent)
        for p in text.split("\n")
    )


