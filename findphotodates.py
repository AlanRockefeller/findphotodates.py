def _pick(prompt, options):
    """Ask the user to pick one of [(label, value)]; returns value or None."""
    for n, (label, _) in enumerate(options, 1):
        print(f"     {n}) {label}")
    answer = _ask(prompt)
    if answer.isdigit() and 1 <= int(answer) <= len(options):
        return options[int(answer) - 1][1]
    return None


