def _build_exiftool_rows(
    batch,
    batch_results,
    locate,
    location_conn,
    location_cache_pending,
    hash_options,
    hash_conn,
    hash_cache_pending,
):
    results = []
    file_counts = Counter()
    stats = {"t_hashing": 0.0, "t_geolocate": 0.0}
    for out_path, os_path, key_path, size_bytes, mtime_ns, ext in batch:
        date_taken, gps_lat, gps_lon = batch_results.get(os_path, (None, None, None))
        location = None
        if locate and gps_lat and gps_lon:
            _tg0 = time.time()
            location = geolocate(
                gps_lat,
                gps_lon,
                location_conn=location_conn,
                pending_counter=location_cache_pending,
            )
            stats["t_geolocate"] += time.time() - _tg0
            if location and is_coordinate_string(location):
                location = None
        _th0 = time.time()
        content_hash = get_content_hash(
            key_path,
            size_bytes,
            mtime_ns,
            hash_options,
            hash_conn,
            hash_cache_pending,
            os_path=os_path,
        )
        stats["t_hashing"] += time.time() - _th0
        results.append(
            (
                out_path,
                date_taken or "",
                size_bytes,
                mtime_ns,
                gps_lat or "",
                gps_lon or "",
                location or "",
                content_hash,
            )
        )
        file_counts[ext] += 1
    return results, file_counts, stats


def _exiftool_worker(
    worker_id,
    work_queue,
    results_queue,
    stop_event,
    locate,
    hash_options,
    hash_conn,
    hash_cache_pending,
    location_conn,
    location_cache_pending,
    error_log,
    error_log_lock,
    throttle=None,
):
    exiftool = None
    worker_started = time.time()
    throttle = throttle or contextlib.nullcontext()
    worker_stats = {
        "worker_id": worker_id,
        "wall": 0.0,
        "t_active": 0.0,
        "t_exiftool": 0.0,
        "t_hashing": 0.0,
        "t_geolocate": 0.0,
        "t_queue_push": 0.0,
        "batches": 0,
        "files": 0,
        "errors": 0,
    }
    try:
        while not stop_event.is_set():
            try:
                batch = work_queue.get(timeout=0.5)
            except queue.Empty:
                continue
            if batch is None:
                break

            _t_active_start = time.time()
            batch_results = None
            read_errors = {}
            t_exiftool = 0.0
            metadata_done_count = 0
            try:
                if exiftool is None:
                    exiftool = ExifToolPersistent()
                    try:
                        exiftool.start()
                    except Exception as e:
                        worker_stats["errors"] += 1
                        results_queue.put(
                            {
                                "type": "fatal_error",
                                "message": (
                                    f"Error: ExifTool worker {worker_id} failed to start: {e}"
                                ),
                            }
                        )
                        stop_event.set()
                        return
                fast2_batch = [
                    item for item in batch if item[5] in SIZE_FILTERED_IMAGE_EXTENSIONS
                ]
                full_batch = [
                    item
                    for item in batch
                    if item[5] not in SIZE_FILTERED_IMAGE_EXTENSIONS
                ]
                batch_results = {}
                read_errors = {}
                if fast2_batch:
                    fast2_paths = [item[1] for item in fast2_batch]
                    _te0 = time.time()
                    with throttle:
                        fast2_results = exiftool.batch_query(fast2_paths, fast2=True)
                    read_errors.update(getattr(exiftool, "last_errors", {}))
                    batch_results.update(fast2_results)
                    t_exiftool += time.time() - _te0
                    metadata_done_count += len(fast2_batch)
                    results_queue.put(
                        {"type": "metadata_done", "input_count": len(fast2_batch)}
                    )
                if full_batch:
                    full_paths = [item[1] for item in full_batch]
                    _te0 = time.time()
                    with throttle:
                        full_results = exiftool.batch_query(full_paths, fast2=False)
                    read_errors.update(getattr(exiftool, "last_errors", {}))
                    batch_results.update(full_results)
                    t_exiftool += time.time() - _te0
                    metadata_done_count += len(full_batch)
                    results_queue.put(
                        {"type": "metadata_done", "input_count": len(full_batch)}
                    )
                worker_stats["t_exiftool"] += t_exiftool
                if batch_results is None:
                    batch_results = {item[1]: (None, None, None) for item in batch}
            except Exception as e:
                worker_stats["errors"] += 1
                _log_worker_error(
                    error_log,
                    error_log_lock,
                    f"Warning: ExifTool worker {worker_id} failed; recording {len(batch)} file(s) with blank EXIF: {e!r}",
                )
                remaining_metadata = len(batch) - metadata_done_count
                if remaining_metadata > 0:
                    results_queue.put(
                        {"type": "metadata_done", "input_count": remaining_metadata}
                    )
                batch_results = {item[1]: (None, None, None) for item in batch}

            results, file_counts, stats = _build_exiftool_rows(
                batch,
                batch_results,
                locate,
                location_conn,
                location_cache_pending,
                hash_options,
                hash_conn,
                hash_cache_pending,
            )
            worker_stats["t_hashing"] += stats["t_hashing"]
            worker_stats["t_geolocate"] += stats["t_geolocate"]
            worker_stats["batches"] += 1
            worker_stats["files"] += len(results)

            packet = {
                "type": "results",
                "input_count": len(batch),
                "results": results,
                "file_counts": file_counts,
                "t_exiftool": t_exiftool,
                "t_hashing": stats["t_hashing"],
                "t_geolocate": stats["t_geolocate"],
                "read_errors": [
                    (item[0], read_errors[item[1]]) for item in batch if item[1] in read_errors
                ],
                "keys": [item[2] for item in batch],
            }
            _tq0 = time.time()
            results_queue.put(packet)
            worker_stats["t_queue_push"] += time.time() - _tq0
            worker_stats["t_active"] += time.time() - _t_active_start
    except Exception as e:
        worker_stats["errors"] += 1
        _log_worker_error(
            error_log,
            error_log_lock,
            f"Warning: ExifTool worker {worker_id} stopped unexpectedly: {e!r}",
        )
    finally:
        if exiftool is not None:
            try:
                exiftool.stop()
            except Exception:
                pass
        worker_stats["wall"] = time.time() - worker_started
        results_queue.put({"type": "worker_done", "stats": worker_stats})


