    args = parser.parse_args()
    output = args.output
    if output is None:
        output = "photo.dates.txt" if args.old_format else "photo.dates.tsv"

    # For --add-hashes, default hash mode to sample (not off) unless user explicitly set it
    effective_hash_mode = args.hash
    if args.add_hashes and args.hash == "off":
        effective_hash_mode = "sample"

    hash_options = parse_hash_args(
        hash_mode=effective_hash_mode,
        sample_chunks=args.sample_chunks,
        sample_chunk_mib=args.sample_chunk_mib,
        hash_algo=args.hash_algo,
        hash_cache_path=args.hash_cache,
        no_hash_cache=args.no_hash_cache,
        hash_exts_str=args.hash_exts,
        quiet=args.quiet,
    )
    location_options = parse_location_args(
        location_cache_path=args.location_cache,
        no_location_cache=args.no_location_cache,
    )

    if args.test:
        test_date_parsing()
        return

    if args.health == "history":
        print_health_history()
        return
    if args.health:
        directory = None if args.directory == "." else _expand_path(args.directory)
        targets = health_targets_for(directory)
        if not targets:
            where = f" holding '{directory}'" if directory else ""
            print(f"No drive{where} found to check.")
            sys.exit(1)
        healthy = run_health_check(
            targets, extended=args.health == "extended", interactive=sys.stdin.isatty()
        )
        sys.exit(0 if healthy else 1)

    # Health checks don't use ExifTool, so check for it only after them.
    try:
        result = subprocess.run(["exiftool", "-ver"], capture_output=True, timeout=5)
        if result.returncode != 0:
            print("Error: ExifTool is required but the 'exiftool' command failed.")
            return
    except FileNotFoundError:
        print("Error: ExifTool is required but was not found.")
        return
    except subprocess.TimeoutExpired:
        print("Error: ExifTool check timed out.")
        return

    migrate_default_hash_cache(quiet=args.quiet, debug=args.debug)

    if args.add_hashes:
        output_abs = _expand_path(output)
        resolved_style = resolve_output_path_style(args.path_style, output_abs, None)
        add_hashes_to_inventory(
            output_abs,
            hash_options,
            quiet=args.quiet,
            debug=args.debug,
            path_style=resolved_style,
        )
