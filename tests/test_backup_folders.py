"""check_photo_backups: a file is never its own backup, and a folder is only
"safe to delete" when everything in it, including subfolders, was checked."""

import sys
from pathlib import Path

import check_photo_backups as checker

COLUMNS = ["filepath", "date_taken", "size_bytes", "mtime_ns", "gps_lat", "gps_lon",
           "location", "content_hash"]


def _write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return path


def _inventory(path, root, rows):
    lines = [f"# inventory_root={root}", "# hash_mode=off", "# Generated by findphotodates.py",
             "\t".join(COLUMNS)]
    for filepath, size in rows:
        lines.append(f"{filepath}\t\t{size}\t1\t\t\t\t")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _run(tmp_path, target, inventories, capsys, *extra):
    out = tmp_path / "out"
    out.mkdir(exist_ok=True)
    argv = ["check_photo_backups.py", "--target", str(target),
            "--inventories", ",".join(str(i) for i in inventories),
            "--out-csv", str(out / "report.csv"), "--missing-list", str(out / "missing.txt"),
            "--safe-list", str(out / "safe.txt"), "--needs-hash-list", str(out / "nh.txt"),
            "--no-verified-match-list", str(out / "nv.txt"),
            "--hash-config-mismatch-list", str(out / "hm.txt"),
            "--allow-weak-without-hash", *extra]
    old = sys.argv
    try:
        sys.argv = argv
        code = checker.main()
    finally:
        sys.argv = old
    printed = capsys.readouterr().out
    safe = (out / "safe.txt").read_text(encoding="utf-8").split()
    return code, printed, safe


def _safe_folders(printed):
    if "=== Directories safe to delete" not in printed:
        return []
    block = printed.split("=== Directories safe to delete", 1)[1].splitlines()[2:]
    return [line.split("/  (")[0].strip() for line in block if "/  (" in line]


def test_a_file_is_not_its_own_backup(tmp_path, capsys):
    target = tmp_path / "laptop" / "Pictures"
    photo = _write(target / "IMG_1.jpg", b"x" * 500)
    # The laptop's own list includes the folder being checked.
    laptop = _inventory(tmp_path / "Laptop.tsv", tmp_path / "laptop", [(photo, 500)])
    code, printed, safe = _run(tmp_path, target, [laptop], capsys)
    assert safe == []
    assert code == 1  # the photo has no backup
    assert "Ignored 1 inventory entries inside" in printed

    backup = _inventory(tmp_path / "Backup.tsv", "/mnt/backup",
                        [("/mnt/backup/Pictures/IMG_1.jpg", 500)])
    code, _printed, safe = _run(tmp_path, target, [laptop, backup], capsys)
    assert safe == [str(photo)]
    assert code == 0


def test_windows_style_rows_for_the_target_are_ignored_too():
    key = checker._path_key("/mnt/c/Users/Me/Pictures")
    assert checker._path_key(r"C:\Users\me\Pictures\a.jpg").startswith(key)
    assert not checker._path_key("/mnt/c/Users/Me/Pictures2/a.jpg").startswith(key)


def test_folders_with_unchecked_files_or_unsafe_subfolders_are_not_safe(tmp_path, capsys):
    target = tmp_path / "card"
    rows = []
    for relative in ("DCIM/100/a.jpg", "DCIM/100/b.jpg", "DCIM/101/c.jpg", "Edits/d.jpg",
                     "Videos/e.mp4", "Videos/sub/f.mp4"):
        _write(target / relative, b"y" * 300)
        rows.append((f"/mnt/backup/{Path(relative).name}", 300))
    _write(target / "DCIM/100/Thumbs.db", b"junk")  # junk doesn't count
    _write(target / "Edits/d.xmp", b"<edits/>")  # an unchecked sidecar: keep the folder
    _write(target / "Videos/sub/g.mov", b"z" * 999)  # no backup anywhere
    backup = _inventory(tmp_path / "Backup.tsv", "/mnt/backup", rows)
    code, printed, safe = _run(tmp_path, target, [backup], capsys)
    folders = _safe_folders(printed)
    # DCIM's whole tree is safe, so only DCIM is listed (not 100 and 101 too).
    assert folders == ["DCIM"]
    # Edits has an unchecked .xmp; Videos has a subfolder with a missing file.
    assert str(target / "Edits" / "d.jpg") in safe  # the photo itself is still safe
    assert "weren't checked" in printed
    assert code == 1


def test_folder_with_only_unchecked_files_and_a_safe_subfolder(tmp_path, capsys):
    target = tmp_path / "card"
    _write(target / "2024" / "notes.txt", b"keep me")  # no photos here, just this
    _write(target / "2024" / "06-30" / "a.jpg", b"y" * 300)
    backup = _inventory(tmp_path / "Backup.tsv", "/mnt/backup", [("/mnt/backup/a.jpg", 300)])
    _code, printed, _safe = _run(tmp_path, target, [backup], capsys)
    assert _safe_folders(printed) == ["2024/06-30"]


def test_whole_target_listed_when_everything_is_safe(tmp_path, capsys):
    target = tmp_path / "card"
    _write(target / "a.jpg", b"y" * 300)
    _write(target / "2024" / "b.jpg", b"y" * 301)
    backup = _inventory(tmp_path / "Backup.tsv", "/mnt/backup",
                        [("/mnt/backup/a.jpg", 300), ("/mnt/backup/b.jpg", 301)])
    _code, printed, _safe = _run(tmp_path, target, [backup], capsys)
    assert _safe_folders(printed) == ["."]


def test_default_extensions_include_common_video_and_raw_types():
    exts = set(checker.DEFAULT_EXTS.split(","))
    assert {"avi", "mkv", "mts", "m4v", "3gp", "rw2", "webp", "heif"} <= exts


def test_target_drive_recognized_by_id_after_a_remount(tmp_path, capsys, monkeypatch):
    mount = tmp_path / "LaCie1"  # the drive's mount point today
    target = mount / "DCIM"
    photo = _write(target / "IMG_1.jpg", b"x" * 500)
    # Its list was made when it was mounted as .../LaCie.
    own = tmp_path / "LaCie.tsv"
    own.write_text("\n".join([
        "# inventory_root=/run/media/me/LaCie", "# volume_ids=D43D-8BB8",
        "# hash_mode=off", "# Generated by findphotodates.py", "\t".join(COLUMNS),
        "/run/media/me/LaCie/DCIM/IMG_1.jpg\t\t500\t1\t\t\t\t",
        "/run/media/me/LaCie/Backup/IMG_1.jpg\t\t500\t1\t\t\t\t",  # a real second copy
    ]) + "\n", encoding="utf-8")
    monkeypatch.setattr(checker, "target_drive", lambda _t: ("D43D-8BB8", str(mount)))
    _code, printed, safe = _run(tmp_path, target, [own], capsys)
    assert "Ignored 1 inventory entries" in printed
    assert safe == [str(photo)]  # the copy in Backup/ still counts

    own.write_text(own.read_text().replace("/run/media/me/LaCie/Backup/IMG_1.jpg\t\t500\t1\t\t\t\t\n", ""))
    _code, _printed, safe = _run(tmp_path, target, [own], capsys)
    assert safe == []
