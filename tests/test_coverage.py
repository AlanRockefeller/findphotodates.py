import csv
import datetime
import os
import tempfile
import unittest
import unittest.mock
from pathlib import Path

import findphotodates as fp
import findphotodates_coverage as cov

FIELDS = ["filepath", "date_taken", "size_bytes", "mtime_ns", "gps_lat", "gps_lon",
          "location", "content_hash"]
TODAY = datetime.date(2026, 11, 1)


def write_list(folder, name, root, rows, label="", volume_id=""):
    path = Path(folder) / f"{name}.tsv"
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(f"# inventory_root={root}\n")
        if label:
            handle.write(f"# volume_label={label}\n")
        if volume_id:
            handle.write(f"# volume_ids={volume_id}\n")
        handle.write("# Generated by findphotodates.py\n")
        writer = csv.writer(handle, delimiter="\t")
        writer.writerow(FIELDS)
        for relative, date, size in rows:
            writer.writerow([f"{root}/{relative}", date, size, 1, "", "", "", ""])
    return path


class CoverageTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.folder = self.temp.name

    def tearDown(self):
        self.temp.cleanup()

    def lists(self, connected=()):
        lists = fp.find_file_lists(self.folder)
        for fl in lists:
            if fl.path.stem in connected:
                fl.drive = fp.DriveInfo("/mnt/x")
        return lists

    def by_name(self, drives):
        return {d.name: d for d in drives}

    def test_copies_are_matched_by_name_size_and_date(self):
        write_list(self.folder, "A", "/a", [
            ("2024/2024-06-30/20240630-DSC_1.NEF", "2024:06:30 10:00:00", 100),
            ("cards/DSC_2.NEF", "2024:06:30 10:00:01", 200),
            ("cards/DSC_3.NEF", "2024:06:30 10:00:02", 300),
            ("cards/notes.txt", "", 50),
        ])
        write_list(self.folder, "B", "/b", [
            ("dump/DSC_1.NEF", "2024:06:30 10:00:00", 100),  # same photo, card name
            ("dump/DSC_2.NEF", "2023:01:01 00:00:00", 200),  # different date taken
            ("dump/DSC_3.NEF", "", 300),  # no date: name and size are enough
        ])
        drives = self.by_name(cov.build_coverage(self.lists(), cov.CoverageSettings(),
                                                 today=TODAY))
        a = drives["A"]
        self.assertEqual(a.total.files, 3)  # the .txt isn't a photo
        self.assertEqual(a.safe.files, 2)
        self.assertEqual(a.only_copy.files, 1)
        self.assertEqual(dict(a.only_copy_folder_files), {"cards": 1})
        self.assertEqual(drives["B"].only_copy.files, 1)

    def test_weak_and_gone_drives_do_not_count_as_safe_copies(self):
        write_list(self.folder, "Main", "/m", [("x/P1.ORF", "2025:01:01 00:00:00", 10),
                                               ("x/P2.ORF", "2025:01:01 00:00:01", 20)])
        write_list(self.folder, "Old", "/o", [("P1.ORF", "2025:01:01 00:00:00", 10)])
        write_list(self.folder, "Wiped", "/w", [("P2.ORF", "2025:01:01 00:00:01", 20)])
        settings = cov.CoverageSettings()
        settings.drive("Old.tsv").role = cov.ROLE_WEAK
        settings.drive("Wiped.tsv").role = cov.ROLE_GONE
        drives = self.by_name(cov.build_coverage(self.lists(), settings, today=TODAY))
        main = drives["Main"]
        self.assertEqual((main.weak_only.files, main.only_copy.files), (1, 1))
        old = drives["Old"]
        self.assertTrue(old.can_retire)
        self.assertIn("Safe to retire", cov.verdict(old))
        self.assertEqual(drives["Wiped"].total.files, 0)
        self.assertIn("Gone", cov.verdict(drives["Wiped"]))

    def test_weak_drive_with_only_copies_is_not_safe_to_retire(self):
        write_list(self.folder, "Old", "/o", [("P1.ORF", "2025:01:01 00:00:00", 10)])
        settings = cov.CoverageSettings()
        settings.drive("Old.tsv").role = cov.ROLE_WEAK
        old = cov.build_coverage(self.lists(), settings, today=TODAY)[0]
        self.assertFalse(old.can_retire)
        self.assertIn("Not safe to retire", cov.verdict(old))

    def test_placeholders_and_system_folders_are_left_out(self):
        write_list(self.folder, "C", "C:", [
            ("Users/me/CrossDevice/Phone/DCIM/PXL_1.jpg", "", 4000),
            ("Windows/Web/wallpaper.jpg", "", 5000),
            ("Users/me/AppData/Local/thumb.jpg", "", 6000),
            ("Users/me/Pictures/real.jpg", "2020:01:01 00:00:00", 7000),
        ])
        drive = cov.build_coverage(self.lists(), cov.CoverageSettings(), today=TODAY)[0]
        self.assertEqual(drive.placeholders.files, 1)
        self.assertEqual(drive.only_copy.files, 1)
        self.assertEqual(drive.total.files, 2)

    def test_automatic_role_follows_drive_health_but_not_cable_errors(self):
        write_list(self.folder, "Ext", "/e", [], label="Ext", volume_id="AAAA-BBBB")
        settings = cov.CoverageSettings()
        cable = [{"date": "2026-10-01 10:00", "drive": "Ext", "health": "WARNING",
                  "connection_errors": "1", "volume_ids": "AAAA-BBBB"}]
        drive = cov.build_coverage(self.lists(), settings, cable, today=TODAY)[0]
        self.assertEqual(drive.role, cov.ROLE_KEEP)
        failing = cable + [{"date": "2026-10-20 10:00", "drive": "Ext", "health": "WARNING",
                            "pending_sectors": "8", "volume_ids": "AAAA-BBBB"}]
        drive = cov.build_coverage(self.lists(), settings, failing, today=TODAY)[0]
        self.assertEqual(drive.role, cov.ROLE_WEAK)
        settings.drive("Ext.tsv").role = cov.ROLE_KEEP
        drive = cov.build_coverage(self.lists(), settings, failing, today=TODAY)[0]
        self.assertEqual((drive.role, drive.role_reason), (cov.ROLE_KEEP, "set by you"))

    def test_backblaze_warning_depends_on_version_history(self):
        write_list(self.folder, "Ext", "/e", [("only.NEF", "2025:01:01 00:00:00", 10)])
        settings = cov.CoverageSettings()
        setting = settings.drive("Ext.tsv")
        setting.backblaze = True
        setting.last_connected = "2026-09-01"  # 61 days before TODAY
        drive = cov.build_coverage(self.lists(), settings, today=TODAY)[0]
        self.assertEqual(drive.backblaze_status, "expired")
        settings.backblaze_history_days = 365
        drive = cov.build_coverage(self.lists(), settings, today=TODAY)[0]
        self.assertEqual(drive.backblaze_status, "ok")
        self.assertIn("304 more days", drive.backblaze_message)
        setting.last_connected = "2025-11-05"  # 361 days
        drive = cov.build_coverage(self.lists(), settings, today=TODAY)[0]
        self.assertEqual(drive.backblaze_status, "soon")
        drive = cov.build_coverage(self.lists(connected=("Ext",)), settings, today=TODAY)[0]
        self.assertEqual(drive.backblaze_status, "ok")
        setting.backblaze = False
        drive = cov.build_coverage(self.lists(), settings, today=TODAY)[0]
        self.assertEqual(drive.backblaze_status, "unprotected")

    def test_settings_round_trip_and_reject_bad_values(self):
        settings = cov.CoverageSettings(backblaze_history_days=365)
        settings.drive("A.tsv").backblaze = True
        settings.drive("A.tsv").role = cov.ROLE_WEAK
        config = settings.to_config({})
        loaded = cov.CoverageSettings.from_config(config)
        self.assertEqual(loaded.backblaze_history_days, 365)
        self.assertEqual((loaded.keep_folders, loaded.keep_library_days), (["Important"], True))
        self.assertEqual(loaded.drives["A.tsv"],
                         cov.DriveSetting(role=cov.ROLE_WEAK, backblaze=True))
        config["coverage"]["backblaze_history_days"] = 90
        config["coverage"]["drives"]["A.tsv"]["role"] = "bogus"
        loaded = cov.CoverageSettings.from_config(config)
        self.assertEqual(loaded.backblaze_history_days, cov.DEFAULT_BACKBLAZE_HISTORY_DAYS)
        self.assertEqual(loaded.drives["A.tsv"].role, cov.ROLE_AUTO)

    def test_record_connected_marks_only_connected_drives(self):
        write_list(self.folder, "On", "/a", [])
        write_list(self.folder, "Off", "/b", [])
        settings = cov.CoverageSettings()
        self.assertTrue(cov.record_connected(settings, self.lists(connected=("On",)), TODAY))
        self.assertEqual(settings.drives["On.tsv"].last_connected, "2026-11-01")
        self.assertNotIn("Off.tsv", settings.drives)
        self.assertFalse(cov.record_connected(settings, self.lists(connected=("On",)), TODAY))

    def test_report_text(self):
        write_list(self.folder, "A", "/a", [("x/y/z/w/v.NEF", "2025:01:01 00:00:00", 2_500_000)])
        settings = cov.CoverageSettings(backblaze_history_days=365)
        text = cov.format_report(cov.build_coverage(self.lists(), settings, today=TODAY),
                                 settings)
        self.assertIn("Backblaze version history: 1 year", text)
        self.assertIn("Only copy of 1 (2.5 MB)", text)
        self.assertIn("x/y/z/w", text)


    def make_drive(self, name, files):
        """A real folder acting as a connected drive, plus its file list.
        *files* maps relative path -> (date taken, size)."""
        mount = Path(self.folder) / "mnt" / name
        rows = []
        for relative, (date, size) in files.items():
            path = mount / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(b"x" * size)
            os.utime(path, ns=(1_000_000_000, 1_000_000_000))
            rows.append((relative, date, size))
        write_list(self.folder, name, str(mount), rows)
        return mount

    def connected_lists(self, *names):
        lists = fp.find_file_lists(self.folder)
        for fl in lists:
            if fl.path.stem in names:
                fl.drive = fp.DriveInfo(str(Path(self.folder) / "mnt" / fl.path.stem))
        return lists

    def test_keep_folders(self):
        self.assertTrue(cov.in_keep_folder("2024/2024-06-30/x.NEF"))
        self.assertTrue(cov.in_keep_folder("Pictures/Lightroom/2024/2024-06-30/x.NEF"))
        self.assertTrue(cov.in_keep_folder("important/Videos/x.mp4"))
        self.assertFalse(cov.in_keep_folder("cards/2024-06-30/x.NEF"))
        self.assertFalse(cov.in_keep_folder("2024/2024-06-30/x.NEF", library_days=False))
        self.assertTrue(cov.in_keep_folder("Archive/x.NEF", keep_folders=["Archive"]))

    def test_cleanup_deletes_only_duplicates_of_kept_copies(self):
        library = self.make_drive("Library", {
            "2024/2024-06-30/20240630-DSC_1.NEF": ("2024:06:30 10:00:00", 11),
            "2024/2024-06-30/20240630-DSC_2.NEF": ("2024:06:30 10:00:01", 12),
            "cards/DSC_5.NEF": ("2024:06:30 10:00:05", 15),  # not in a keep folder
        })
        cards = self.make_drive("Cards", {
            "dump/DSC_1.NEF": ("2024:06:30 10:00:00", 11),  # duplicate: delete
            "dump/DSC_2.NEF": ("2024:01:01 00:00:00", 12),  # different date: keep
            "dump/DSC_3.NEF": ("", 13),  # no copy: keep
            "dump/DSC_5.NEF": ("2024:06:30 10:00:05", 15),  # copy not in keep folder
            "Important/DSC_1.NEF": ("2024:06:30 10:00:00", 11),  # keep folder: never
        })
        lists = self.connected_lists("Library", "Cards")
        target = Path(self.folder) / "Cards.tsv"
        plan = cov.plan_cleanup(lists, cov.CoverageSettings(), target)
        self.assertEqual([Path(i.path).name for i in plan.items], ["DSC_1.NEF"])
        self.assertEqual(plan.kept_without_copy, 3)
        log = Path(self.folder) / "logs" / "cleanup.tsv"
        counts, freed = cov.run_cleanup(plan, log)
        self.assertEqual((counts["deleted"], freed), (1, 11))
        self.assertFalse((cards / "dump/DSC_1.NEF").exists())
        self.assertTrue((cards / "Important/DSC_1.NEF").exists())
        self.assertTrue((library / "2024/2024-06-30/20240630-DSC_1.NEF").exists())
        with log.open() as handle:
            rows = list(csv.DictReader(handle, delimiter="\t"))
        self.assertEqual(rows[0]["status"], "deleted")
        self.assertTrue(rows[0]["kept copy"].endswith("20240630-DSC_1.NEF"))

    def test_cleanup_checks_kept_copy_and_respects_roles(self):
        library = self.make_drive("Library", {
            "Important/a.mp4": ("2020:01:01 00:00:00", 20),
            "Important/b.mp4": ("2020:01:01 00:00:01", 21)})
        self.make_drive("Cards", {"a.mp4": ("2020:01:01 00:00:00", 20),
                                  "b.mp4": ("2020:01:01 00:00:01", 21)})
        target = Path(self.folder) / "Cards.tsv"
        settings = cov.CoverageSettings()
        settings.drive("Library.tsv").role = cov.ROLE_WEAK
        plan = cov.plan_cleanup(self.connected_lists("Library", "Cards"), settings, target)
        self.assertEqual(plan.items, [])  # copies on a weak drive don't count
        settings.drive("Library.tsv").role = cov.ROLE_KEEP
        plan = cov.plan_cleanup(self.connected_lists("Library", "Cards"), settings, target)
        self.assertEqual(len(plan.items), 2)
        (library / "Important/b.mp4").unlink()  # the kept copy vanished since the scan
        counts, _ = cov.run_cleanup(plan, Path(self.folder) / "log.tsv")
        self.assertEqual(counts["deleted"], 1)
        self.assertEqual(counts["kept: other copy not found on disk"], 1)

    def test_cleanup_with_disconnected_kept_drive_needs_trust(self):
        self.make_drive("Library", {"Important/a.mp4": ("2020:01:01 00:00:00", 20)})
        cards = self.make_drive("Cards", {"a.mp4": ("2020:01:01 00:00:00", 20)})
        target = Path(self.folder) / "Cards.tsv"
        lists = self.connected_lists("Cards")
        plan = cov.plan_cleanup(lists, cov.CoverageSettings(), target)
        counts, _ = cov.run_cleanup(plan, Path(self.folder) / "log.tsv")
        self.assertEqual(counts["kept: other copy's drive isn't connected"], 1)
        self.assertTrue((cards / "a.mp4").exists())
        counts, _ = cov.run_cleanup(plan, Path(self.folder) / "log.tsv", trust_lists=True)
        self.assertEqual(counts["deleted"], 1)

    def test_cleanup_keeps_file_when_kept_copy_is_now_cloud_only(self):
        self.make_drive("Library", {"Important/a.mp4": ("2020:01:01 00:00:00", 20)})
        cards = self.make_drive("Cards", {"a.mp4": ("2020:01:01 00:00:00", 20)})
        plan = cov.plan_cleanup(self.connected_lists("Library", "Cards"),
                                cov.CoverageSettings(), Path(self.folder) / "Cards.tsv")
        log = Path(self.folder) / "log.tsv"
        with unittest.mock.patch.object(fp, "is_placeholder_stat", lambda st: True):
            counts, _ = cov.run_cleanup(plan, log)
        self.assertEqual(counts["kept: other copy not found on disk"], 1)
        self.assertTrue((cards / "a.mp4").exists())
        self.assertEqual(len(log.read_text().splitlines()), 2)  # written straight away

