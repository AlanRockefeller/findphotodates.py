import csv
import os
import tempfile
import unittest
from pathlib import Path

from findphotodates_search import (
    InventorySearchIndex,
    SearchQueryError,
    compile_query,
    normalize_photo_day,
)

FIELDS = [
    "filepath",
    "date_taken",
    "size_bytes",
    "mtime_ns",
    "gps_lat",
    "gps_lon",
    "location",
    "content_hash",
]


def write_inventory(path, rows):
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write("# Generated by findphotodates.py\n")
        writer = csv.DictWriter(handle, fieldnames=FIELDS, delimiter="\t")
        writer.writeheader()
        writer.writerows(rows)


def paths(index, query, **kwargs):
    return [row.filepath for row in index.search(query, **kwargs)[0]]


class InventorySearchTests(unittest.TestCase):
    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        root = Path(self.temp_dir.name)
        self.camera = root / "Camera.tsv"
        self.archive = root / "Archive.tsv"
        write_inventory(
            self.camera,
            [
                {
                    "filepath": "/photos/New York/Sunset.JPG",
                    "date_taken": "2024:06:30 10:00:00",
                    "size_bytes": "12000000",
                    "mtime_ns": "1719766800000000000",
                    "gps_lat": "40.7",
                    "gps_lon": "-74.0",
                    "location": "New York, USA",
                    "content_hash": "abc123",
                },
                {
                    "filepath": "/docs/report.pdf",
                    "date_taken": "",
                    "size_bytes": "5000",
                    "mtime_ns": "1600000000000000000",
                    "gps_lat": "",
                    "gps_lon": "",
                    "location": "",
                    "content_hash": "",
                },
            ],
        )
        write_inventory(
            self.archive,
            [
                {
                    "filepath": "/old/family portrait.png",
                    "date_taken": "1999:12:31 23:00:00",
                    "size_bytes": "2500000",
                    "mtime_ns": "946681200000000000",
                    "gps_lat": "51.5",
                    "gps_lon": "-0.1",
                    "location": "London, UK",
                    "content_hash": "def456",
                }
            ],
        )
        self.index = InventorySearchIndex(root / "search.sqlite3")
        self.assertEqual(self.index.refresh([self.camera, self.archive]), (2, 3))

    def tearDown(self):
        self.temp_dir.cleanup()

    def test_plain_text_and_field_searches(self):
        self.assertEqual(paths(self.index, "sun"), ["/photos/New York/Sunset.JPG"])
        self.assertEqual(
            paths(self.index, 'location:"New York"'), ["/photos/New York/Sunset.JPG"]
        )
        self.assertEqual(
            paths(self.index, "ext:jpg|heic"), ["/photos/New York/Sunset.JPG"]
        )
        self.assertEqual(paths(self.index, "ext!=jpg|png"), ["/docs/report.pdf"])
        self.assertEqual(
            paths(self.index, "hash=abc123"), ["/photos/New York/Sunset.JPG"]
        )
        self.assertEqual(
            paths(self.index, "list:Archive"), ["/old/family portrait.png"]
        )
        self.assertEqual(
            paths(self.index, "date=2024-06-30"), ["/photos/New York/Sunset.JPG"]
        )
        self.assertNotIn(
            "/photos/New York/Sunset.JPG", paths(self.index, "date!=2024-06-30")
        )

    def test_ranges_missing_values_wildcards_and_exclusions(self):
        self.assertEqual(
            paths(self.index, "date>=2024-01 size>10MB"),
            ["/photos/New York/Sunset.JPG"],
        )
        self.assertEqual(paths(self.index, "date:missing"), ["/docs/report.pdf"])
        self.assertEqual(paths(self.index, "lat>45"), ["/old/family portrait.png"])
        self.assertEqual(
            paths(self.index, "path:*portrait.png"), ["/old/family portrait.png"]
        )
        self.assertEqual(
            set(paths(self.index, "-ext:pdf")),
            {"/photos/New York/Sunset.JPG", "/old/family portrait.png"},
        )

    def test_search_can_be_limited_to_selected_lists(self):
        self.assertEqual(
            set(paths(self.index, "", source_paths=[self.camera])),
            {"/photos/New York/Sunset.JPG", "/docs/report.pdf"},
        )
        self.assertEqual(
            paths(self.index, "", source_paths=[self.archive]),
            ["/old/family portrait.png"],
        )

    def test_refresh_reuses_unchanged_lists_and_replaces_changed_ones(self):
        self.assertEqual(self.index.refresh([self.camera, self.archive]), (0, 3))
        write_inventory(
            self.camera,
            [
                {
                    "filepath": "/new.mov",
                    "date_taken": "",
                    "size_bytes": "9",
                    "mtime_ns": "1",
                    "gps_lat": "",
                    "gps_lon": "",
                    "location": "",
                    "content_hash": "",
                }
            ],
        )
        stat = self.camera.stat()
        os.utime(self.camera, ns=(stat.st_atime_ns, stat.st_mtime_ns + 1_000_000))
        self.assertEqual(self.index.refresh([self.camera, self.archive]), (1, 2))
        self.assertEqual(paths(self.index, "list:Camera"), ["/new.mov"])

    def test_bad_queries_have_useful_errors(self):
        with self.assertRaisesRegex(SearchQueryError, "Unknown field"):
            compile_query("camera:nikon")
        with self.assertRaisesRegex(SearchQueryError, "Sizes look like"):
            compile_query("size>large")
        with self.assertRaisesRegex(SearchQueryError, "quote"):
            compile_query('location:"New York')

    def test_photo_day_input_is_normalized_and_validated(self):
        self.assertEqual(normalize_photo_day("2024-06-30"), "2024-06-30")
        self.assertEqual(normalize_photo_day("06/30/2024"), "2024-06-30")
        with self.assertRaisesRegex(SearchQueryError, "YYYY-MM-DD"):
            normalize_photo_day("2024-02-30")
