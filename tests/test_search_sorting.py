"""Sorting search results by a column: every match is covered, page by page."""

import csv

from findphotodates_search import FolderResult, InventorySearchIndex, sort_folders

FIELDS = ["filepath", "date_taken", "size_bytes", "mtime_ns", "gps_lat", "gps_lon",
          "location", "content_hash"]
COUNT = 2300  # more than the 2000 folders the old folder view stopped at


def _index(tmp_path):
    listing = tmp_path / "Camera.tsv"
    with listing.open("w", encoding="utf-8", newline="") as handle:
        handle.write("# Generated by findphotodates.py\n")
        writer = csv.DictWriter(handle, fieldnames=FIELDS, delimiter="\t")
        writer.writeheader()
        for number in range(COUNT):
            writer.writerow({
                "filepath": f"/photos/dir{number % 40:02d}/IMG_{number:05d}.jpg",
                "date_taken": f"2024:01:{number % 28 + 1:02d} 10:00:00",
                # Many ties on size, so the tie-break has to be stable too.
                "size_bytes": str((number * 7919) % 1000),
                "mtime_ns": str(1_600_000_000_000_000_000 + number),
                "gps_lat": "", "gps_lon": "", "location": "", "content_hash": "",
            })
    index = InventorySearchIndex(tmp_path / "search.sqlite3")
    index.refresh([listing])
    return index


def _all_pages(index, sort, query=""):
    rows = []
    offset = 0
    while True:
        page, more = index.search(query, limit=500, offset=offset, sort=sort)
        rows.extend(page)
        offset += len(page)
        if not more:
            return rows


def test_sorted_by_size_pages_cover_every_match_in_order(tmp_path):
    index = _index(tmp_path)
    rows = _all_pages(index, ("size", True))
    assert len(rows) == COUNT
    assert len({row.filepath for row in rows}) == COUNT
    sizes = [row.size_bytes for row in rows]
    assert sizes == sorted(sizes, reverse=True)
    assert sizes[0] == 999 and sizes[-1] == 0


def test_ascending_path_sort_ignores_case(tmp_path):
    index = _index(tmp_path)
    rows = _all_pages(index, ("path", False))
    paths = [row.filepath.lower() for row in rows]
    assert len(paths) == COUNT
    assert paths == sorted(paths)


def test_sort_applies_to_matches_only(tmp_path):
    index = _index(tmp_path)
    rows = _all_pages(index, ("date", False), query="dir07")
    assert rows and all("/dir07/" in row.filepath for row in rows)
    dates = [row.date_taken for row in rows]
    assert dates == sorted(dates)


def test_unknown_sort_column_keeps_the_default_order(tmp_path):
    index = _index(tmp_path)
    plain, _ = index.search("", limit=20)
    unknown, _ = index.search("", limit=20, sort=("nonsense", True))
    assert [row.filepath for row in plain] == [row.filepath for row in unknown]


def _folder(path, files, size, first, last, modified):
    return FolderResult("/lists/Camera.tsv", path, files, size, first, last, modified)


def test_folders_sort_by_each_column_and_reverse():
    folders = [
        _folder("/b", 5, 300, "2024-02-01", "2024-02-02", 10),
        _folder("/a", 9, 100, "", "", 30),
        _folder("/c", 1, 200, "2023-05-05", "2024-01-01", 20),
    ]
    assert [f.filepath for f in sort_folders(folders, "path")] == ["/a", "/b", "/c"]
    assert [f.filepath for f in sort_folders(folders, "path", True)] == ["/c", "/b", "/a"]
    assert [f.filepath for f in sort_folders(folders, "location")] == ["/c", "/b", "/a"]
    assert [f.filepath for f in sort_folders(folders, "size", True)] == ["/b", "/c", "/a"]
    assert [f.filepath for f in sort_folders(folders, "date")] == ["/a", "/c", "/b"]
    assert [f.filepath for f in sort_folders(folders, "modified", True)] == ["/a", "/c", "/b"]
    assert [f.filepath for f in sort_folders(folders, "nonsense")] == ["/b", "/a", "/c"]
